"""
stls_core_handshake.py
----------------------
STLS handshake with proof-of-key-possession via an HMAC challenge/response.

The key never travels over the channel. The flow is:

    Client                              Server
      │                                   │
      │  POST /stls/handshake             │
      │  { client_id, nonce }  ─────────► │
      │                                   │  kid  = provider.getSessionKeyIdentifier()
      │                                   │  key  = provider.getSessionKeyData(kid)
      │                                   │  sid  = uuid4()               ← server generates it
      │                                   │  proof= HMAC-SHA256(key, nonce)
      │                                   │  SessionCache.put(sid, transport)
      │  ◄─────────────────────────────   │
      │  { session_id, kid, proof }       │
      │                                   │
      │  own_proof = HMAC(own_key, nonce) │
      │  assert own_proof == proof        │ ← mutual proof of possession
      │                                   │
      │  POST /stls/a2a (encrypted)       │
      │  X-STLS-Session-ID: sid ────────► │  SessionCache.get(sid) → transport

Guarantees:
  - session_id generated by the server → not controllable by the client
  - proof demonstrates that the server possesses the same key as the client
  - no key material ever in transit in either direction
  - replay attack mitigated: single-use 32-byte random nonce per handshake

The HTTP layer (stls-a2a, stls-mcp) registers POST /stls/handshake and calls
perform_handshake(). The client-side verification is in verify_handshake_proof().
"""

from __future__ import annotations

import asyncio
import base64
import hmac as _hmac
import inspect
import logging
import os
import uuid
from hashlib import sha256
from typing import Any, Optional

from pydantic import BaseModel, Field

from .stls_core_constants import STLS_VERSION, HANDSHAKE_PATH
from .stls_core_crypto import StlsTransport
from .stls_core_session import SessionCache, SessionCacheBase

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Pydantic models — wire format
# ---------------------------------------------------------------------------

class HandshakeRequest(BaseModel):
    """
    Body of the POST /stls/handshake request.

    Attributes:
        client_id:  Client identifier (e.g. "mcp-client-1").
                    Used for logging and audit — not authentication.
        nonce:      32 random bytes generated by the client, base64-encoded.
                    The server uses it to compute the HMAC proof.
                    Single-use: a new nonce for every handshake.
        protocol:   Expected STLS protocol version (default "1.0").
    """
    client_id: str = Field(..., description="Client identifier")
    nonce: str = Field(
        ...,
        description="32 random bytes base64-encoded, generated by the client",
    )
    protocol: str = Field(default=STLS_VERSION)

    @classmethod
    def generate(cls, client_id: str) -> "HandshakeRequest":
        """
        Factory: generates a HandshakeRequest with a random nonce.
        Used by the STLS client before calling POST /stls/handshake.
        """
        nonce = base64.b64encode(os.urandom(32)).decode("utf-8")
        return cls(client_id=client_id, nonce=nonce)


class HandshakeResponse(BaseModel):
    """
    Body of the handshake response.

    Attributes:
        session_id:     UUID generated by the server — the session identifier.
                        The client uses it in X-STLS-Session-ID on every request.
        kid:            Key identifier assigned by the provider.
                        The client uses it in X-STLS-Kid for correlation/debugging.
        proof:          HMAC-SHA256(session_key, nonce) base64-encoded.
                        The client verifies that the server possesses the same key.
        protocol:       Protocol version confirmed by the server.
        encryption:     Encryption algorithm in use.
        hmac:           HMAC algorithm in use.
        key_derivation: Key derivation scheme in use.
    """
    session_id: str
    kid: str
    proof: str = Field(..., description="HMAC-SHA256(key, nonce) base64-encoded")
    protocol: str = Field(default=STLS_VERSION)
    encryption: str = Field(default="AES-256-GCM")
    hmac: str = Field(default="HMAC-SHA256")
    key_derivation: str = Field(default="HKDF-Expand-SHA256")


# ---------------------------------------------------------------------------
# HandshakeError
# ---------------------------------------------------------------------------

class HandshakeError(Exception):
    """
    Raised by perform_handshake() on error.

    Attributes:
        message: Error description.
        code:    JSON-RPC code (-32603 internal, -32600 bad request).
    """
    def __init__(self, message: str, code: int = -32603) -> None:
        super().__init__(message)
        self.message = message
        self.code = code


# ---------------------------------------------------------------------------
# Server-side: perform_handshake()
# ---------------------------------------------------------------------------

async def perform_handshake(
    request: HandshakeRequest,
    key_session_provider: Any,
    session_cache: SessionCacheBase,
) -> HandshakeResponse:
    """
    Runs the server side of the STLS handshake.

    Called by the route handler for POST /stls/handshake in stls-a2a and stls-mcp.
    The caller deserializes the request and serializes the HTTP response.

    Flow:
        1. Decodes the client's nonce.
        2. Gets the kid from the provider.
        3. Gets the session_key from the provider via the kid.
        4. Generates the session_id (uuid4 — server-side).
        5. Computes proof = HMAC-SHA256(session_key, nonce).
        6. Builds the StlsTransport and registers it in SessionCache.
        7. Returns the HandshakeResponse with session_id, kid, proof.

    Args:
        request:              HandshakeRequest validated by Pydantic.
        key_session_provider: KeySessionProvider instance (base or arqit_py).
        session_cache:        SessionCache shared with the middleware.

    Returns:
        HandshakeResponse with session_id, kid and proof.

    Raises:
        HandshakeError: If the provider fails to supply a valid key
                        or the nonce is malformed.
    """
    # ── 1. Decode nonce ───────────────────────────────────────────────────
    try:
        nonce = base64.b64decode(request.nonce)
        if len(nonce) < 16:
            raise HandshakeError(
                f"Nonce troppo corto: {len(nonce)} byte (minimo 16)",
                code=-32600,
            )
    except HandshakeError:
        raise
    except Exception as exc:
        raise HandshakeError(
            f"Nonce non è base64 valido: {exc}", code=-32600
        ) from exc

    session_id = str(uuid.uuid4())

    logger.info(
        "Handshake avviato: client_id=%s session_id=%s",
        request.client_id, session_id,
    )

    # ── 2. Get the kid from the provider ──────────────────────────────────────
    try:
        kid_result = key_session_provider.getSessionKeyIdentifier()
        kid = await _resolve(kid_result)
        if not kid:
            raise HandshakeError(
                "getSessionKeyIdentifier() ha restituito None o stringa vuota"
            )
    except HandshakeError:
        raise
    except Exception as exc:
        raise HandshakeError(f"Errore nel recupero del kid: {exc}") from exc

    # ── 3. Get the session_key from the provider ─────────────────────────────
    try:
        raw_result = key_session_provider.getSessionKeyData(kid)
        raw_key = await _resolve_blocking(raw_result)
    except HandshakeError:
        raise
    except Exception as exc:
        raise HandshakeError(
            f"Errore nel recupero della session key (kid={kid!r}): {exc}"
        ) from exc

    if raw_key is None:
        raise HandshakeError(
            f"getSessionKeyData({kid!r}) ha restituito None"
        )

    try:
        session_key = bytes(raw_key)
    except Exception as exc:
        raise HandshakeError(
            f"Impossibile convertire session key in bytes "
            f"(type={type(raw_key).__name__}): {exc}"
        ) from exc

    if not session_key:
        raise HandshakeError("Session key vuota")

    # ── 4. Compute proof = HMAC-SHA256(session_key, nonce) ───────────────────
    proof_bytes = _hmac.new(session_key, nonce, sha256).digest()
    proof = base64.b64encode(proof_bytes).decode("utf-8")

    # ── 5. Build the transport and register it in the cache ──────────────────
    # session_cache.put() receives the raw data (session_id, kid, session_key)
    # and builds the StlsTransport internally — needed for Redis serialization
    # (InMemorySessionCache and RedisSessionCache share the same API).
    try:
        session_cache.put(session_id, kid, session_key)
    except Exception as exc:
        raise HandshakeError(
            f"Errore nella registrazione della sessione in cache: {exc}"
        ) from exc

    logger.info(
        "Handshake completato: session_id=%s kid=%s client_id=%s "
        "key_len=%d cache_size=%d",
        session_id, kid, request.client_id,
        len(session_key), len(session_cache),
    )

    return HandshakeResponse(
        session_id=session_id,
        kid=kid,
        proof=proof,
    )


# ---------------------------------------------------------------------------
# Client-side: verify_handshake_proof()
# ---------------------------------------------------------------------------

def verify_handshake_proof(
    session_key: bytes,
    nonce: str,
    response: HandshakeResponse,
) -> bool:
    """
    Verifies, on the client side, that the server possesses the same key.

    The client computes HMAC-SHA256(own_key, nonce) and compares it
    against the proof received in the HandshakeResponse. If they match,
    the server and client have the same session_key — proof of possession
    without the key ever being transmitted.

    Args:
        session_key: Client's session key (from the local provider).
        nonce:       Original nonce sent in the HandshakeRequest (base64).
        response:    HandshakeResponse received from the server.

    Returns:
        True if the proof is valid, False otherwise.

    Raises:
        ValueError: If nonce or proof are not valid base64.
    """
    nonce_bytes = base64.b64decode(nonce)
    expected_proof = _hmac.new(session_key, nonce_bytes, sha256).digest()
    received_proof = base64.b64decode(response.proof)

    # Timing-safe comparison
    return _hmac.compare_digest(expected_proof, received_proof)


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

async def _resolve(result: Any) -> Any:
    """Resolves a coroutine, a Java future, or a direct value."""
    if inspect.isawaitable(result):
        return await result
    if hasattr(result, "get") and callable(result.get):
        return result.get()
    return result


async def _resolve_blocking(result: Any) -> Any:
    """
    Like _resolve, but for blocking operations (Arqit network I/O):
    runs on the loop's default executor to avoid blocking asyncio.

    Uses the loop's default executor (a shared thread pool, lazily created
    by asyncio) instead of instantiating a new one on every call: a
    ThreadPoolExecutor dedicated to a single handshake means creating and
    tearing down an OS thread on every single handshake — avoidable
    overhead on the most frequent path of the arqit_py provider.
    """
    if inspect.isawaitable(result):
        return await result
    if not (hasattr(result, "get") and callable(result.get)):
        return result
    loop = asyncio.get_event_loop()
    return await loop.run_in_executor(None, result.get)
