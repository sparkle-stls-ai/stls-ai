"""
stls_core_session.py
--------------------
STLS session model and protocol-agnostic cache with interchangeable backends.

Contents:
  - StlsSession        : dataclass aggregating session_id, kid, StlsTransport
  - SessionCacheBase   : ABC for the active sessions store
  - InMemorySessionCache : in-process LRU+TTL (default)
  - RedisSessionCache  : Redis-backed, for multi-instance deployments
  - SessionCacheFactory: selects the backend from SESSION_CACHE_BACKEND
  - SessionCache       : alias of InMemorySessionCache (backward compat)

Environment variables:
  SESSION_CACHE_BACKEND         memory (default) | redis
  SESSION_CACHE_REDIS_URL       redis://localhost:6379
  SESSION_CACHE_REDIS_NAMESPACE stls:sc  (Redis key prefix)
  SESSION_CACHE_TTL             idle TTL in seconds (default 3600)
  STLS_SESSION_CACHE_MAX        max sessions in the memory cache (default 256)
  STLS_SESSION_TTL              alias of SESSION_CACHE_TTL for compatibility
  SESSION_KEY_MAX_AGE_SECONDS   absolute key-rotation max-age in seconds.
                                 Unset or <=0 (default): disabled, behavior
                                 unchanged from before this existed. >0:
                                 get() also expires a session once its AGE
                                 (since creation, not since last access)
                                 exceeds this value, regardless of how
                                 recently it was used — on top of, not
                                 instead of, the idle TTL above. Per-process
                                 config (server-side only, never client
                                 settable) — see issue #6.
  STLS_CORE_ATREST_KEY          base64-encoded 32-byte wrapping key (KEK).
                                 Unset (default): the Redis payload below
                                 is stored in the clear, as before this
                                 existed (a warning is logged once).
                                 Set: the payload is additionally
                                 AES-256-GCM-sealed (see stls_core_atrest.py)
                                 before SET and opened after GET — see
                                 issue #20. Shared with
                                 RedisArqitKeyStore; domain-separated via
                                 HKDF so one KEK safely serves both.

Redis layout:
  {prefix}:{session_id}  →  JSON {"enc_aes_key": "<base64>",
                                   "dec_aes_key": "<base64>",
                                   "enc_hmac_key": "<base64>",
                                   "dec_hmac_key": "<base64>",
                                   "kid": "<kid>", "created_at": <timestamp>}
                             — optionally AES-256-GCM-sealed as a whole
                             when STLS_CORE_ATREST_KEY is set (see above).
                             Only the already-HKDF-derived AES/HMAC keys
                             are stored, never the raw session_key passed
                             to put() — see issue #20.
                             TTL = SESSION_CACHE_TTL (idle timeout, renewed on get)
                             created_at also drives the max-age check above
                             when SESSION_KEY_MAX_AGE_SECONDS is set — every
                             instance reads the same shared record, so no
                             cross-instance coordination is needed.

  The default prefix "stls:sc" cleanly separates sessions from the
  keystore entries ("stls:ks:...") — no collision even on a Redis
  instance shared between client and server.

Backward compatibility:
  SessionCache = InMemorySessionCache  (alias)

Public interface (SessionCacheBase):
  put(session_id, kid, session_key)  → None
  get(session_id)                    → Optional[StlsTransport]
  remove(session_id)                 → bool
  purge_expired()                    → int
  __len__(), __contains__()
"""

from __future__ import annotations

import base64
import json
import logging
import os
import time
from abc import ABC, abstractmethod
from collections import OrderedDict
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Optional

from .stls_core_atrest import AtRestCipher
from .stls_core_crypto import DerivedKeys, StlsTransport

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# StlsSession — record of an active session
# ---------------------------------------------------------------------------

@dataclass
class StlsSession:
    """
    Represents an active STLS session.

    Attributes:
        session_id:    Unique UUID generated by the server during the handshake.
        kid:           Arqit (or base) key identifier. Useful for audit and
                       correlation with the stls:ks:* entries in Redis.
        transport:     StlsTransport initialized with the derived session_key.
        created_at:    UTC creation timestamp.
        peer_identity: Peer identity (optional, from the KeyProvider).
    """

    session_id: str
    kid: str
    transport: StlsTransport
    created_at: datetime = field(
        default_factory=lambda: datetime.now(timezone.utc)
    )
    peer_identity: Optional[str] = None

    def age_seconds(self) -> float:
        return (datetime.now(timezone.utc) - self.created_at).total_seconds()

    def __repr__(self) -> str:
        return (
            f"StlsSession(session_id={self.session_id!r}, "
            f"kid={self.kid!r}, "
            f"peer={self.peer_identity!r}, "
            f"age={self.age_seconds():.0f}s)"
        )


# ---------------------------------------------------------------------------
# SessionCacheBase — ABC
# ---------------------------------------------------------------------------

class SessionCacheBase(ABC):
    """
    Common interface for the active STLS sessions store.

    Implementations: InMemorySessionCache, RedisSessionCache.
    Backend selected by SessionCacheFactory.build().

    The put() method receives the raw data (session_id, kid, session_key)
    instead of a StlsTransport object, to allow serialization to Redis.
    Each implementation internally builds the appropriate transport.
    get() always returns a ready-to-use StlsTransport.
    """

    @abstractmethod
    def put(self, session_id: str, kid: str, session_key: bytes) -> None:
        """
        Registers a new STLS session after a completed handshake.

        Args:
            session_id:  UUID generated by the server (lookup key).
            kid:         Arqit key identifier — kept for audit and
                         correlation with stls:ks:* in Redis.
            session_key: Raw 32-byte key from which StlsTransport derives
                         the AES and HMAC keys via HKDF.
        """

    @abstractmethod
    def get(self, session_id: str) -> Optional[StlsTransport]:
        """
        Retrieves the transport for an active session.

        Renews the idle TTL on every access (sliding window).
        Returns None if the session does not exist or has expired.
        """

    @abstractmethod
    def remove(self, session_id: str) -> bool:
        """Explicitly removes a session. Returns True if it existed."""

    @abstractmethod
    def purge_expired(self) -> int:
        """Removes expired sessions. Returns the number removed."""

    @abstractmethod
    def __len__(self) -> int: ...

    @abstractmethod
    def __contains__(self, session_id: str) -> bool: ...


# ---------------------------------------------------------------------------
# InMemorySessionCache — in-process LRU + TTL
# ---------------------------------------------------------------------------

class InMemorySessionCache(SessionCacheBase):
    """
    In-process LRU+TTL cache. Default for development and single-instance deployments.

    Does not survive a process restart nor a multi-instance scale-out.
    For multi-replica Cloud Run use RedisSessionCache instead.

    Internal structure:
      OrderedDict[session_id → (StlsTransport, kid, last_access_float, created_at_float)]

    created_at is set once, at first insertion, and never refreshed by
    get()/put()-on-update — unlike last_access, which slides. Both clocks
    use time.monotonic(), immune to wall-clock adjustments.
    """

    def __init__(
        self,
        max_size: Optional[int] = None,
        ttl_seconds: Optional[int] = None,
        max_age_seconds: Optional[int] = None,
    ) -> None:
        self._max_size: int = max_size or int(
            os.getenv("STLS_SESSION_CACHE_MAX", "256")
        )
        self._ttl: int = ttl_seconds or int(
            os.getenv("SESSION_CACHE_TTL",
                os.getenv("STLS_SESSION_TTL", "3600"))
        )
        self._max_age: int = (
            max_age_seconds if max_age_seconds is not None
            else int(os.getenv("SESSION_KEY_MAX_AGE_SECONDS", "0"))
        )
        self._store: OrderedDict[str, tuple[StlsTransport, str, float, float]] = OrderedDict()
        logger.debug(
            "InMemorySessionCache inizializzata: max=%d ttl=%ds max_age=%ds",
            self._max_size, self._ttl, self._max_age,
        )

    def put(self, session_id: str, kid: str, session_key: bytes) -> None:
        now = time.monotonic()
        transport = StlsTransport(session_key=session_key, session_id=session_id)

        existing = self._store.get(session_id)
        if existing is not None:
            # Preserves the original created_at — a put() on an already
            # known session_id is a redundant/idempotent re-registration,
            # not a brand new session, so its max-age clock must not reset.
            _, __, ___, created_at = existing
            self._store.move_to_end(session_id)
            self._store[session_id] = (transport, kid, now, created_at)
            logger.debug("InMemorySessionCache.put: aggiornata %s", session_id)
            return

        if len(self._store) >= self._max_size:
            evicted_id, _ = self._store.popitem(last=False)
            logger.info(
                "InMemorySessionCache: evizione LRU %s (max=%d)",
                evicted_id, self._max_size,
            )

        self._store[session_id] = (transport, kid, now, now)
        self._store.move_to_end(session_id)
        logger.debug("InMemorySessionCache.put: nuova sessione %s kid=%s", session_id, kid)

    def get(self, session_id: str) -> Optional[StlsTransport]:
        entry = self._store.get(session_id)
        if entry is None:
            return None

        transport, kid, last_access, created_at = entry
        now = time.monotonic()

        if now - last_access > self._ttl:
            del self._store[session_id]
            logger.info(
                "InMemorySessionCache: sessione %s scaduta (TTL=%ds)",
                session_id, self._ttl,
            )
            return None

        if self._max_age > 0 and now - created_at > self._max_age:
            del self._store[session_id]
            logger.info(
                "InMemorySessionCache: sessione %s scaduta per max-age (max_age=%ds, eta'=%.0fs)",
                session_id, self._max_age, now - created_at,
            )
            return None

        # LRU refresh + sliding TTL (created_at is NOT refreshed here)
        self._store.move_to_end(session_id)
        self._store[session_id] = (transport, kid, now, created_at)
        return transport

    def remove(self, session_id: str) -> bool:
        if session_id in self._store:
            del self._store[session_id]
            logger.debug("InMemorySessionCache.remove: %s", session_id)
            return True
        return False

    def purge_expired(self) -> int:
        now = time.monotonic()
        expired = [
            sid for sid, (_, __, last, created_at) in self._store.items()
            if now - last > self._ttl
            or (self._max_age > 0 and now - created_at > self._max_age)
        ]
        for sid in expired:
            del self._store[sid]
        if expired:
            logger.info(
                "InMemorySessionCache.purge_expired: rimossi %d sessioni",
                len(expired),
            )
        return len(expired)

    def __len__(self) -> int:
        return len(self._store)

    def __contains__(self, session_id: str) -> bool:
        return session_id in self._store

    def __repr__(self) -> str:
        return (
            f"InMemorySessionCache(size={len(self._store)}, "
            f"max={self._max_size}, ttl={self._ttl}s, max_age={self._max_age}s)"
        )


# ---------------------------------------------------------------------------
# RedisSessionCache — Redis backend for multi-instance deployments
# ---------------------------------------------------------------------------

class RedisSessionCache(SessionCacheBase):
    """
    STLS sessions cache on Redis. For multi-replica, stateless Cloud Run deployments.

    Redis layout:
      {prefix}:{session_id}  →  JSON string, optionally AES-256-GCM-sealed
                                 as a whole (see below)   TTL = ttl_seconds
                                 (idle timeout)

    The JSON contains:
      {
        "enc_aes_key":  "<base64>",            ← already-HKDF-derived keys;
        "dec_aes_key":  "<base64>",              the raw session_key passed
        "enc_hmac_key": "<base64>",              to put() is never stored —
        "dec_hmac_key": "<base64>",              see issue #20.
        "kid":          "<kid>",               ← audit and correlation with stls:ks:*
        "created_at":   <unix timestamp float>  ← absolute creation time (wall
                                                   clock); drives the max-age
                                                   check below when enabled.
      }

    If STLS_CORE_ATREST_KEY is set, this JSON is AES-256-GCM-sealed as a
    whole (AtRestCipher, see stls_core_atrest.py) before SET and opened
    after GET — independent of Redis's own at-rest settings. If unset,
    the JSON above is stored in the clear, as before encryption-at-rest
    existed (a warning is logged once, at construction).

    The TTL is sliding (renewed on every get() via GETEX) — a session
    expires only after SESSION_CACHE_TTL seconds of inactivity. On top of
    that, if max_age_seconds > 0, get() also expires a session once
    time.time() - created_at exceeds it, regardless of how recently it was
    used. created_at lives in the one shared Redis record, so every
    instance in a multi-replica deployment computes the same expiry
    decision from the same data — no cross-instance coordination needed
    for this check (see issue #6).

    No collision with the keystore (stls:ks:...) nor with other sessions:
      - session_id is a UUID4 (uniqueness guaranteed by the server)
      - the default prefix "stls:sc" is distinct from "stls:ks"
      - works correctly even on a Redis instance shared between client and
        server, because only the server writes to this namespace.
    """

    def __init__(
        self,
        redis_url: str = "redis://localhost:6379",
        prefix: str = "stls:sc",
        ttl_seconds: int = 3600,
        max_age_seconds: int = 0,
    ) -> None:
        try:
            import redis as redis_lib
        except ImportError as exc:
            raise ImportError(
                "redis>=7.4.0 is required for SESSION_CACHE_BACKEND=redis. "
                "Install it with: pip install 'redis>=7.4.0'"
            ) from exc

        self._r = redis_lib.Redis.from_url(redis_url, decode_responses=True)
        self._prefix = prefix
        self._ttl = ttl_seconds
        self._max_age = max_age_seconds

        self._cipher = AtRestCipher.from_env(label=b"stls-core/session-cache")
        if self._cipher is None:
            logger.warning(
                "RedisSessionCache: STLS_CORE_ATREST_KEY is not set — session "
                "cache entries are stored in plaintext (see issue #20)."
            )

        logger.info(
            "RedisSessionCache inizializzata: prefix=%s url=%s ttl=%ds max_age=%ds",
            prefix, redis_url, ttl_seconds, max_age_seconds,
        )

    def _key(self, session_id: str) -> str:
        return f"{self._prefix}:{session_id}"

    def put(self, session_id: str, kid: str, session_key: bytes) -> None:
        # Derives the AES/HMAC keys once and discards session_key — only
        # the derived keys below are ever written to Redis (issue #20).
        derived = StlsTransport.derive_keys(session_key)
        payload = json.dumps({
            "enc_aes_key":  base64.b64encode(derived.enc_aes_key).decode(),
            "dec_aes_key":  base64.b64encode(derived.dec_aes_key).decode(),
            "enc_hmac_key": base64.b64encode(derived.enc_hmac_key).decode(),
            "dec_hmac_key": base64.b64encode(derived.dec_hmac_key).decode(),
            "kid":          kid,
            "created_at":   time.time(),
        }).encode("utf-8")

        value = (
            base64.b64encode(self._cipher.seal(payload)).decode()
            if self._cipher is not None
            else payload.decode("utf-8")
        )
        self._r.set(self._key(session_id), value, ex=self._ttl)
        logger.debug(
            "RedisSessionCache.put: session_id=%s kid=%s ttl=%ds",
            session_id, kid, self._ttl,
        )

    def get(self, session_id: str) -> Optional[StlsTransport]:
        # GETEX: returns the value AND renews the TTL (sliding idle timeout)
        raw = self._r.getex(self._key(session_id), ex=self._ttl)
        if raw is None:
            logger.debug("RedisSessionCache.get: %s non trovata", session_id)
            return None

        try:
            payload = self._cipher.open(base64.b64decode(raw)) if self._cipher is not None else raw.encode("utf-8")
            data = json.loads(payload)
            derived = DerivedKeys(
                enc_aes_key=base64.b64decode(data["enc_aes_key"]),
                dec_aes_key=base64.b64decode(data["dec_aes_key"]),
                enc_hmac_key=base64.b64decode(data["enc_hmac_key"]),
                dec_hmac_key=base64.b64decode(data["dec_hmac_key"]),
            )
        except Exception as exc:
            logger.error(
                "RedisSessionCache.get: errore deserializzazione session_id=%s: %s",
                session_id, exc,
            )
            return None

        if self._max_age > 0:
            created_at = data.get("created_at")
            age = time.time() - created_at if created_at is not None else 0.0
            if age > self._max_age:
                self._r.delete(self._key(session_id))
                logger.info(
                    "RedisSessionCache: sessione %s scaduta per max-age (max_age=%ds, eta'=%.0fs)",
                    session_id, self._max_age, age,
                )
                return None

        return StlsTransport.from_derived_keys(derived, session_id=session_id)

    def remove(self, session_id: str) -> bool:
        deleted = self._r.delete(self._key(session_id))
        if deleted:
            logger.debug("RedisSessionCache.remove: %s", session_id)
        return bool(deleted)

    def purge_expired(self) -> int:
        # Redis handles eviction automatically via TTL.
        # This method is a no-op, kept for interface compatibility.
        return 0

    def __len__(self) -> int:
        # KEYS is O(N) — acceptable for diagnostics, not for the hot path.
        return len(self._r.keys(f"{self._prefix}:*"))

    def __contains__(self, session_id: str) -> bool:
        return bool(self._r.exists(self._key(session_id)))

    def __repr__(self) -> str:
        return (
            f"RedisSessionCache(prefix={self._prefix!r}, ttl={self._ttl}s, "
            f"max_age={self._max_age}s)"
        )


# ---------------------------------------------------------------------------
# SessionCacheFactory
# ---------------------------------------------------------------------------

class SessionCacheFactory:
    """
    Builds the SessionCache backend based on SESSION_CACHE_BACKEND.

    Environment variables:
      SESSION_CACHE_BACKEND         memory (default) | redis
      SESSION_CACHE_REDIS_URL       redis://localhost:6379
      SESSION_CACHE_REDIS_NAMESPACE stls:sc  (Redis key prefix)
      SESSION_CACHE_TTL             idle TTL in seconds (default 3600)
      STLS_SESSION_CACHE_MAX        max sessions (memory only, default 256)
      SESSION_KEY_MAX_AGE_SECONDS   absolute key-rotation max-age in seconds,
                                     both backends. Unset or <=0: disabled
                                     (default, no behavior change).
    """

    @staticmethod
    def build() -> SessionCacheBase:
        """
        Creates the appropriate SessionCache instance.

        Returns:
            InMemorySessionCache if SESSION_CACHE_BACKEND=memory (default).
            RedisSessionCache    if SESSION_CACHE_BACKEND=redis.
        """
        backend  = os.getenv("SESSION_CACHE_BACKEND", "memory").strip().lower()
        max_age  = int(os.getenv("SESSION_KEY_MAX_AGE_SECONDS", "0"))

        if backend == "redis":
            url    = os.getenv("SESSION_CACHE_REDIS_URL", "redis://localhost:6379")
            prefix = os.getenv("SESSION_CACHE_REDIS_NAMESPACE", "stls:sc")
            ttl    = int(os.getenv("SESSION_CACHE_TTL",
                         os.getenv("STLS_SESSION_TTL", "3600")))
            return RedisSessionCache(
                redis_url=url, prefix=prefix, ttl_seconds=ttl, max_age_seconds=max_age,
            )

        if backend == "memory":
            return InMemorySessionCache(max_age_seconds=max_age)

        raise ValueError(
            f"SESSION_CACHE_BACKEND='{backend}' non riconosciuto. "
            "Valori supportati: 'memory' (default), 'redis'."
        )


