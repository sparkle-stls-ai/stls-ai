"""
stls_core_handshake_pqc.py
--------------------------
STLS handshake with hybrid X25519 + ML-KEM-768 key agreement.

Dedicated endpoint: POST /stls/pqc/handshake
(distinct from POST /stls/handshake, active when KEY_PROVIDER_NAME=pqc)

Full flow:

    Client                                          Server
      │                                               │
      │  [KeyProviderClientPQC.start()]               │
      │  generates X25519 + ML-KEM-768 keypair        │
      │                                               │
      │  POST /stls/pqc/handshake                     │
      │  { client_id, nonce,              ─────────►  │  perform_pqc_handshake()
      │    x25519_pub, mlkem_pub }                     │    ① generates server X25519 keypair
      │                                               │    ② X25519 DH → x25519_secret
      │                                               │    ③ ML-KEM encap → (ct, mlkem_secret)
      │                                               │    ④ HKDF(x25519‖mlkem, salt=nonce)
      │                                               │       → session_key
      │                                               │    ⑤ proof = HMAC(session_key, nonce)
      │                                               │    ⑥ session_cache.put(sid, kid, key)
      │  ◄─────────────────────────────────────────   │
      │  { session_id, kid, proof,                    │
      │    server_x25519_pub, mlkem_ct }              │
      │                                               │
      │  derive_session_key_client()                  │
      │    X25519 DH(client_priv, server_pub)         │
      │    ML-KEM decap(client_sec, mlkem_ct)         │
      │    HKDF(x25519‖mlkem, salt=nonce)             │
      │    → session_key                              │
      │                                               │
      │  verify_pqc_handshake_proof()                 │
      │    assert HMAC(own_key, nonce) == proof  ✓    │
      │                                               │
      │  POST /stls/secure-a2a (encrypted)            │
      │  X-STLS-Session-ID: session_id  ───────────►  │  SessionCache.get(session_id) → transport

Guarantees (inherited from the standard handshake + quantum-safety):
  - session_id generated by the server → not controllable by the client
  - proof demonstrates mutual possession of the same derived key
  - no key material in transit (only pubkeys + KEM ciphertext)
  - ML-KEM-768: resistant to Shor's algorithm (NIST Level 3)
  - X25519: fallback should ML-KEM ever have an unknown vulnerability
  - nonce as HKDF salt: freshness guaranteed for every session
"""

from __future__ import annotations

import base64
import hmac as _hmac
import logging
import os
import uuid
from hashlib import sha256

from pydantic import BaseModel, Field

from .stls_core_constants import STLS_VERSION, HANDSHAKE_PQC_PATH
from .stls_core_session import SessionCacheBase
from .providers.stls_core_providers_pqc import (
    mlkem_decap,
    mlkem_encap,
    x25519_exchange,
    x25519_generate_keypair,
    derive_hybrid_key,
)

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Wire models
# ---------------------------------------------------------------------------

class PQCHandshakeRequest(BaseModel):
    """
    Body of the POST /stls/pqc/handshake request.

    Extends the standard HandshakeRequest format with the client's KEM pubkeys.

    Attributes:
        client_id:          Client identifier (logging/audit).
        nonce:              32 random bytes base64 — HMAC proof + HKDF salt.
        x25519_public_key:  Client's X25519 pubkey (32 bytes, base64).
        mlkem_public_key:   Client's ML-KEM-768 pubkey (base64).
        protocol:           STLS protocol version (default "1.0").
    """
    client_id: str = Field(..., description="Client identifier")
    nonce: str = Field(..., description="32 random bytes base64 — single-use")
    x25519_public_key: str = Field(..., description="Client X25519 pubkey, 32 bytes base64")
    mlkem_public_key: str = Field(..., description="Client ML-KEM-768 pubkey, base64")
    protocol: str = Field(default=STLS_VERSION)

    @classmethod
    def generate(
        cls,
        client_id: str,
        x25519_public_key_bytes: bytes,
        mlkem_public_key_bytes: bytes,
    ) -> "PQCHandshakeRequest":
        """
        Factory: generates a PQCHandshakeRequest with a random nonce.

        Used by the STLS client before calling POST /stls/pqc/handshake.

        Args:
            client_id:               Client identifier.
            x25519_public_key_bytes: X25519 pubkey (from KeyProviderClientPQC).
            mlkem_public_key_bytes:  ML-KEM-768 pubkey (from KeyProviderClientPQC).
        """
        return cls(
            client_id=client_id,
            nonce=base64.b64encode(os.urandom(32)).decode("utf-8"),
            x25519_public_key=base64.b64encode(x25519_public_key_bytes).decode("utf-8"),
            mlkem_public_key=base64.b64encode(mlkem_public_key_bytes).decode("utf-8"),
        )


class PQCHandshakeResponse(BaseModel):
    """
    Body of the POST /stls/pqc/handshake response.

    Attributes:
        session_id:               UUID generated by the server — used in X-STLS-Session-ID.
        kid:                      UUID of the derived key — used in X-STLS-Kid.
        proof:                    HMAC-SHA256(session_key, nonce) base64.
        server_x25519_public_key: Server's X25519 pubkey (32 bytes, base64).
        mlkem_ciphertext:         ML-KEM-768 ciphertext (base64).
        protocol:                 STLS protocol version.
        encryption:               Encryption algorithm.
        hmac:                     HMAC algorithm.
        key_derivation:           Key derivation scheme.
    """
    session_id: str
    kid: str
    proof: str = Field(..., description="HMAC-SHA256(session_key, nonce) base64")
    server_x25519_public_key: str = Field(..., description="Server X25519 pubkey, 32 bytes base64")
    mlkem_ciphertext: str = Field(..., description="ML-KEM-768 ciphertext, base64")
    protocol: str = Field(default=STLS_VERSION)
    encryption: str = Field(default="AES-256-GCM")
    hmac: str = Field(default="HMAC-SHA256")
    key_derivation: str = Field(default="HKDF-SHA256+X25519+ML-KEM-768")


# ---------------------------------------------------------------------------
# PQCHandshakeError
# ---------------------------------------------------------------------------

class PQCHandshakeError(Exception):
    """
    Raised by perform_pqc_handshake() on error.

    Attributes:
        message: Error description.
        code:    JSON-RPC code (-32603 internal, -32600 bad request).
    """
    def __init__(self, message: str, code: int = -32603) -> None:
        super().__init__(message)
        self.message = message
        self.code = code


# ---------------------------------------------------------------------------
# Server-side: perform_pqc_handshake()
# ---------------------------------------------------------------------------

async def perform_pqc_handshake(
    request: PQCHandshakeRequest,
    session_cache: SessionCacheBase,
) -> PQCHandshakeResponse:
    """
    Runs the server side of the PQC handshake.

    Unlike perform_handshake(), this does not require a key_session_provider
    because the session_key is derived locally via the KEM — no external
    service involved. The derived key is saved directly in the
    session_cache with the server-generated session_id and kid.

    Flow:
        1. Decodes and validates the client's nonce and pubkeys.
        2. Generates a server-side X25519 keypair (fresh for every handshake).
        3. X25519 DH: x25519_secret = DH(server_priv, client_x25519_pub).
        4. ML-KEM-768 encap: (mlkem_ct, mlkem_secret) = encap(client_mlkem_pub).
        5. HKDF: session_key = HKDF(x25519_secret ‖ mlkem_secret, salt=nonce).
        6. Generates session_id (uuid4) and kid (uuid4).
        7. Computes proof = HMAC-SHA256(session_key, nonce).
        8. Registers the session: session_cache.put(session_id, kid, session_key).
        9. Returns the PQCHandshakeResponse with server_x25519_pub + mlkem_ct.

    Args:
        request:       PQCHandshakeRequest validated by Pydantic.
        session_cache: SessionCacheBase shared with the encrypted middleware.

    Returns:
        PQCHandshakeResponse with session_id, kid, proof and the server's KEM material.

    Raises:
        PQCHandshakeError: If the pubkeys are malformed or a KEM operation fails.
    """

    # ── 1. Decode and validate input ──────────────────────────────────────────
    try:
        nonce = base64.b64decode(request.nonce)
        if len(nonce) < 16:
            raise PQCHandshakeError(
                f"Nonce troppo corto: {len(nonce)} byte (minimo 16)",
                code=-32600,
            )
    except PQCHandshakeError:
        raise
    except Exception as exc:
        raise PQCHandshakeError(f"Nonce non è base64 valido: {exc}", code=-32600) from exc

    try:
        client_x25519_pub = base64.b64decode(request.x25519_public_key)
        if len(client_x25519_pub) != 32:
            raise PQCHandshakeError(
                f"x25519_public_key deve essere 32 byte, "
                f"ricevuto {len(client_x25519_pub)}",
                code=-32600,
            )
    except PQCHandshakeError:
        raise
    except Exception as exc:
        raise PQCHandshakeError(
            f"x25519_public_key non è base64 valido: {exc}", code=-32600
        ) from exc

    try:
        client_mlkem_pub = base64.b64decode(request.mlkem_public_key)
    except Exception as exc:
        raise PQCHandshakeError(
            f"mlkem_public_key non è base64 valido: {exc}", code=-32600
        ) from exc

    session_id = str(uuid.uuid4())
    kid = str(uuid.uuid4())   # PQC kid = fresh UUID, distinct for every session

    logger.info(
        "PQC Handshake avviato: client_id=%s session_id=%s",
        request.client_id, session_id,
    )

    # ── 2. Generate the server-side X25519 keypair ────────────────────────────
    try:
        server_x25519_priv, server_x25519_pub = x25519_generate_keypair()
    except Exception as exc:
        raise PQCHandshakeError(f"Errore generazione keypair X25519: {exc}") from exc

    # ── 3. X25519 DH exchange ─────────────────────────────────────────────────
    try:
        x25519_secret = x25519_exchange(server_x25519_priv, client_x25519_pub)
    except Exception as exc:
        raise PQCHandshakeError(f"X25519 DH exchange fallito: {exc}") from exc

    # ── 4. ML-KEM-768 encapsulation ───────────────────────────────────────────
    try:
        mlkem_ciphertext, mlkem_secret = mlkem_encap(client_mlkem_pub)
    except Exception as exc:
        raise PQCHandshakeError(f"ML-KEM encapsulation fallita: {exc}") from exc

    # ── 5. Derive the hybrid session_key via HKDF ─────────────────────────────
    try:
        session_key = derive_hybrid_key(
            x25519_secret=x25519_secret,
            mlkem_secret=mlkem_secret,
            nonce=nonce,
        )
    except Exception as exc:
        raise PQCHandshakeError(f"HKDF derivazione fallita: {exc}") from exc

    # ── 6. Compute proof = HMAC-SHA256(session_key, nonce) ────────────────────
    proof_bytes = _hmac.new(session_key, nonce, sha256).digest()
    proof = base64.b64encode(proof_bytes).decode("utf-8")

    # ── 7. Register the session in the cache ──────────────────────────────────
    try:
        session_cache.put(session_id, kid, session_key)
    except Exception as exc:
        raise PQCHandshakeError(f"Errore registrazione sessione in cache: {exc}") from exc

    logger.info(
        "PQC Handshake completato: session_id=%s kid=%s client_id=%s key_len=%d",
        session_id, kid, request.client_id, len(session_key),
    )

    return PQCHandshakeResponse(
        session_id=session_id,
        kid=kid,
        proof=proof,
        server_x25519_public_key=base64.b64encode(server_x25519_pub).decode("utf-8"),
        mlkem_ciphertext=base64.b64encode(mlkem_ciphertext).decode("utf-8"),
    )


# ---------------------------------------------------------------------------
# Client-side: derive_session_key_client() + verify_pqc_handshake_proof()
# ---------------------------------------------------------------------------

def derive_session_key_client(
    client_x25519_private_key_bytes: bytes,
    client_mlkem_secret_key_bytes: bytes,
    response: PQCHandshakeResponse,
    nonce: str,
) -> bytes:
    """
    Derives the session_key on the client side after receiving the PQCHandshakeResponse.

    Runs the client side of the hybrid KEM: X25519 DH with the server's
    pubkey + ML-KEM decapsulation with the server's ciphertext. Applies
    the same HKDF as the server with the same nonce → identical session_key.

    Args:
        client_x25519_private_key_bytes:  X25519 private key (from KeyProviderClientPQC).
        client_mlkem_secret_key_bytes:    ML-KEM-768 secret key (from KeyProviderClientPQC).
        response:                         PQCHandshakeResponse received from the server.
        nonce:                            Nonce sent in the PQCHandshakeRequest (base64).

    Returns:
        32-byte session_key — must match the one derived by the server.
        To be passed to StlsTransport(session_key, session_id) to start
        the encrypted communication.
    """
    nonce_bytes = base64.b64decode(nonce)
    server_x25519_pub = base64.b64decode(response.server_x25519_public_key)
    mlkem_ct = base64.b64decode(response.mlkem_ciphertext)

    # X25519 DH (client side) — mirrors the server: same shared secret
    x25519_secret = x25519_exchange(
        client_x25519_private_key_bytes,
        server_x25519_pub,
    )

    # ML-KEM decapsulation — recovers mlkem_secret from the ciphertext
    mlkem_secret = mlkem_decap(client_mlkem_secret_key_bytes, mlkem_ct)

    # Hybrid HKDF — same derivation as the server, same inputs → same key
    session_key = derive_hybrid_key(
        x25519_secret=x25519_secret,
        mlkem_secret=mlkem_secret,
        nonce=nonce_bytes,
    )

    logger.debug("[PQC client] session_key derivata: len=%d", len(session_key))
    return session_key


def verify_pqc_handshake_proof(
    session_key: bytes,
    nonce: str,
    response: PQCHandshakeResponse,
) -> bool:
    """
    Verifies, on the client side, that the server derived the same session_key.

    Computes HMAC-SHA256(own_key, nonce) and compares it against the
    server's proof. If they match, the server correctly ran the KEM and
    holds the same key — proof of possession without the key ever being
    transmitted.

    Args:
        session_key: Session_key derived client-side (from derive_session_key_client()).
        nonce:       Nonce sent in the PQCHandshakeRequest (base64).
        response:    PQCHandshakeResponse received from the server.

    Returns:
        True if the proof is valid, False otherwise.

    Raises:
        ValueError: If nonce or proof are not valid base64.
    """
    nonce_bytes = base64.b64decode(nonce)
    expected = _hmac.new(session_key, nonce_bytes, sha256).digest()
    received = base64.b64decode(response.proof)
    return _hmac.compare_digest(expected, received)
