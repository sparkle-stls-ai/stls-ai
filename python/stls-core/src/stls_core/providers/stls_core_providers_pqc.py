_MLKEM_CANDIDATES = ("ML-KEM-768", "Kyber768")
_MLKEM_ALG_CACHE: Optional[str] = None


# ---------------------------------------------------------------------------
# PQCKeyStore — in-memory store for keys derived via the KEM
# ---------------------------------------------------------------------------

class PQCKeyStore:
    """
    Thread-safe in-memory store for session keys derived via PQC.

    Unlike ArqitKeyStoreBase (which handles asynchronous keys from
    external peering), PQCKeyStore is a plain dict because PQC keys
    are derived locally and synchronously during the handshake.

    The TTL is managed by the SessionCache at a higher level — this
    class only maintains the kid → bytes correlation for the lookup in
    getSessionKeyData().
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._keys: dict[str, bytes] = {}

    def put(self, kid: str, key_bytes: bytes) -> None:
        """Saves a key derived via the KEM."""
        with self._lock:
            self._keys[kid] = key_bytes
        logger.debug("[PQCKeyStore] key saved: kid=%s len=%d", kid, len(key_bytes))

    def get(self, kid: str) -> Optional[bytes]:
        """Retrieves the key associated with the kid, or None."""
        with self._lock:
            return self._keys.get(kid)

    def remove(self, kid: str) -> bool:
        """Removes the key. Returns True if it existed."""
        with self._lock:
            return bool(self._keys.pop(kid, None))

    def __len__(self) -> int:
        with self._lock:
            return len(self._keys)


# ---------------------------------------------------------------------------
# KeySessionProviderPQC
# ---------------------------------------------------------------------------

class KeySessionProviderPQC(KeySessionProvider):
    """
    KeySessionProvider for the PQC provider.

    SERVER: the key is injected via inject_key() by
    perform_pqc_handshake() after the KEM exchange. getSessionKeyIdentifier()
    and getSessionKeyData() expose it to the standard pipeline.

    CLIENT: holds the X25519 and ML-KEM keypairs generated by
    KeyProviderClientPQC.start(), exposed as properties for the client-side
    KEM (decap + DH) after the PQCHandshakeResponse.
    """

    def __init__(
        self,
        session_type: KeySessionProvider.KeySessionProviderType,
        key_store: PQCKeyStore,
        x25519_private_key_bytes: Optional[bytes] = None,
        mlkem_secret_key_bytes: Optional[bytes] = None,
    ) -> None:
        self._session_type = session_type
        self._key_store = key_store
        self._kid: Optional[str] = None
        # Client only — keypair for the client-side KEM
        self._x25519_private_key_bytes = x25519_private_key_bytes
        self._mlkem_secret_key_bytes = mlkem_secret_key_bytes

    def getSessionType(self) -> KeySessionProvider.KeySessionProviderType:
        return self._session_type

    async def getSessionKeyIdentifier(self, hint_kid: Optional[str] = None) -> str:
        """
        Returns the kid of the current session.

        SERVER: the kid is injected by inject_key() from
        perform_pqc_handshake() before this is called.
        CLIENT: the kid is set via setSessionKeyIdentifier()
        after receiving the PQCHandshakeResponse.

        hint_kid is ignored: pqc never goes through perform_handshake()
        (it has its own dedicated /stls/pqc/handshake flow via
        perform_pqc_handshake()), and there is only ever one
        unambiguous kid per instance regardless.
        """
        if self._kid is None:
            raise RuntimeError(
                "[KeySessionProviderPQC] kid not available — "
                "inject_key() or setSessionKeyIdentifier() not yet called"
            )
        return self._kid

    def setSessionKeyIdentifier(self, kid: str) -> None:
        self._kid = kid
        logger.debug("[KeySessionProviderPQC] kid set: %s", kid)

    async def getSessionKeyData(self, session_key_identifier: str) -> bytes:
        """Returns the key derived via the KEM for the given kid."""
        key = self._key_store.get(session_key_identifier)
        if key is None:
            raise KeyError(
                f"[KeySessionProviderPQC] key not found: "
                f"kid={session_key_identifier!r}"
            )
        return key

    def inject_key(self, kid: str, session_key: bytes) -> None:
        """
        Injects the key derived by perform_pqc_handshake() into the key store.

        Called by the server after every KEM exchange to make the key
        available to getSessionKeyData() and update the current kid.
        Every PQC handshake produces a distinct kid (UUID), so this
        instance can serve subsequent handshakes with no reuse risk.
        """
        self._key_store.put(kid, session_key)
        self._kid = kid
        logger.debug(
            "[KeySessionProviderPQC] key injected: kid=%s len=%d",
            kid, len(session_key),
        )

    def getPeerIdentity(self) -> Optional[str]:
        return None

    def releaseSessionKeyData(self, session_key_identifier: str) -> None:
        """Evicts the kid from the in-memory PQCKeyStore (single-process, safe)."""
        self._key_store.remove(session_key_identifier)

    # ── Client-only: KEM derivation ──────────────────────────────────────────
    #
    # x25519_private_key_bytes/mlkem_secret_key_bytes used to be public
    # properties, read directly by stls-mcp's/stls-a2a's client handshake
    # code (issue #5, "Restrict stls-core's public API surface" — this is
    # ephemeral KEM private key material, never meant to leave this class).
    # derive_client_key() is now the only way to use them from outside.

    def derive_client_key(
        self,
        server_x25519_public_key_bytes: bytes,
        mlkem_ciphertext: bytes,
        nonce: bytes,
    ) -> bytes:
        """
        Derives the shared session key from this CLIENT session's own
        ephemeral KEM private material and the server's public
        contribution (already-decoded raw bytes from the handshake
        response, not the response DTO itself — callers already have it
        decoded, and this keeps this module decoupled from the wire-format
        modules' types).
        """
        if self._x25519_private_key_bytes is None or self._mlkem_secret_key_bytes is None:
            raise RuntimeError(
                "[KeySessionProviderPQC] derive_client_key() requires a CLIENT "
                "session with KEM private material (server session?)"
            )
        x25519_secret = x25519_exchange(self._x25519_private_key_bytes, server_x25519_public_key_bytes)
        mlkem_secret = mlkem_decap(self._mlkem_secret_key_bytes, mlkem_ciphertext)
        return derive_hybrid_key(x25519_secret, mlkem_secret, nonce)

    def destroy_private_key_material(self) -> None:
        """Best-effort zeroing of this session's own KEM private key material."""
        if self._x25519_private_key_bytes:
            self._x25519_private_key_bytes = b"\x00" * len(self._x25519_private_key_bytes)
        if self._mlkem_secret_key_bytes:
            self._mlkem_secret_key_bytes = b"\x00" * len(self._mlkem_secret_key_bytes)


