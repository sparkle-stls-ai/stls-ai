"""
stls_mcp_server.py
-------------------
Server-side entry point of stls-mcp: create_secure_mcp_app(mcp).

Mounts two paths side by side on the same FastMCP instance:

    MCP_PLAIN_PATH ("/mcp")      → Starlette app generated by the official
                                    SDK, intact, zero modifications. Any
                                    spec-compliant MCP client (Claude
                                    Desktop, claude.ai, MCP Inspector, ...)
                                    uses it with no idea STLS exists.

    MCP_STLS_PATH ("/mcp-stls")  → StlsMcpMiddleware, which decrypts
                                    inbound, forwards internally to the
                                    SAME standard app (same session
                                    manager, same tool/resource/prompt
                                    surface), and encrypts the outbound
                                    response.

    HANDSHAKE_PATH ("/stls/handshake") → stls_core's HMAC
                                    challenge/response endpoint, shared
                                    with stls-a2a.

Critical detail (official SDK mcp.server.fastmcp): the FastMCP session
manager MUST be started via the outer ASGI app's lifespan, otherwise
requests fail silently. This module correctly propagates
mcp.session_manager.run() into the resulting Starlette app's lifespan —
exactly as documented by the SDK for the
"FastAPI(lifespan=lambda app: mcp.session_manager.run())" pattern,
adapted to plain Starlette (without introducing a FastAPI dependency
into stls-mcp).
"""

from __future__ import annotations

import logging
import os
from contextlib import asynccontextmanager
from typing import Any, AsyncIterator

from starlette.applications import Starlette
from starlette.requests import Request
from starlette.responses import JSONResponse
from starlette.routing import Mount, Route

from stls_core import HandshakeRequest, KeySessionProvider, SessionCache, SessionCacheBase, SessionCacheFactory, perform_handshake
from stls_core.stls_core_handshake import HandshakeError

from .stls_mcp_constants import (
    MCP_PLAIN_PATH,
    MCP_STLS_PATH,
)
from .stls_mcp_middleware import StlsMcpMiddleware
from .stls_mcp_auth import AuthConfig, wrap_with_auth

logger = logging.getLogger(__name__)

try:
    from stls_core import HANDSHAKE_PATH
except ImportError:  # pragma: no cover
    HANDSHAKE_PATH = "/stls/handshake"

try:
    from stls_core import HANDSHAKE_PQC_PATH
except ImportError:  # pragma: no cover
    HANDSHAKE_PQC_PATH = "/stls/pqc/handshake"


class _ExactMountPathNormalizer:
    """
    Workaround for a Starlette characteristic (verified on 1.3.1, but
    present in earlier versions too): `Mount(prefix, app=...)` generates
    a regex `^{prefix}/(?P<path>.*)$` — which requires a slash *after*
    the prefix. A request to the exact path, with nothing after it
    (e.g. "POST /mcp-stls", no trailing slash), does NOT match that
    Mount: Starlette moves on to evaluate the next routes and ends up
    matching `Mount("/", ...)` (whose regex `^/(?P<path>.*)$` literally
    intercepts any path), instead of returning a 404 or correctly
    routing to the STLS middleware.

    This is a real problem for us: MCP clients (including Claude
    Desktop) typically call the exact configured path, with no trailing
    slash.

    Solution: wrap the entire app with this normalizer, which intercepts
    the scope BEFORE it reaches Starlette's router and adds the missing
    slash when the path exactly matches the target prefix. It must act
    upstream of the router (not inside a Mount) because otherwise the
    match failure already happens before any middleware nested inside
    that Mount is ever invoked.
    """

    def __init__(self, app: Any, prefix: str) -> None:
        self._app = app
        self._prefix = prefix

    async def __call__(self, scope: Any, receive: Any, send: Any) -> None:
        if scope.get("type") == "http" and scope.get("path") == self._prefix:
            scope = dict(scope)
            scope["path"] = self._prefix + "/"
            scope["raw_path"] = scope["path"].encode("utf-8")
        await self._app(scope, receive, send)


def create_secure_mcp_app(
    mcp: Any,
    key_session_provider: KeySessionProvider,
    *,
    stls_path: str = MCP_STLS_PATH,
    plain_path: str = MCP_PLAIN_PATH,
    session_cache: SessionCacheBase | None = None,
    auth: AuthConfig | None = None,
    api_key_manager: Any | None = None,
) -> Any:
    """
    Builds the complete ASGI app with plain + STLS-encrypted MCP endpoints.

    Args:
        mcp:                  mcp.server.fastmcp.FastMCP instance with the
                              tools/resources/prompts already registered by
                              the developer. Not modified in any way.
        key_session_provider: KeySessionProvider (base or arqit_py, from
                              stls_core.providers) used by the handshake
                              endpoint to resolve kid/session_key.
        stls_path:            path of the encrypted endpoint (default "/mcp-stls").
        plain_path:            FUNCTIONALLY REQUIRED (no longer just
                              cosmetic/for logging — fixed bug: StlsMcpMiddleware
                              used to ignore this parameter and always use
                              the module constant "/mcp" for the internal
                              rewrite, so with a custom plain_path the
                              encrypted request got forwarded to the wrong
                              internal path → 500 client-side). MUST match
                              exactly the `streamable_http_path` argument
                              passed to `mcp`'s constructor (default "/mcp")
                              — that's what decides the REAL path of the
                              standard endpoint; this parameter only needs
                              to mirror it, so StlsMcpMiddleware can
                              correctly compute where to forward decrypted
                              requests internally. streamable_http_app()
                              already includes that route internally, which
                              is why it's mounted on Mount("/", ...) rather
                              than Mount(plain_path, ...) (which would
                              produce a doubled path, e.g. "/mcp/mcp").
        session_cache:         SessionCacheBase to share with the handshake
                              endpoint and the STLS middleware. If None, a
                              new one is created (default behavior for a
                              single process).
        auth:                  static AuthConfig (stls_mcp_auth.AuthConfig),
                              in-memory, timing-safe. None (default) = no
                              validation — unchanged behavior for callers
                              not using it.
        api_key_manager:       enterprise ApiKeyManager (stls_core.auth,
                              Redis/File/Postgres). If provided, takes
                              priority over ``auth``. UNLIKE stls-a2a: pass
                              an instance that is NOT yet started —
                              start/stop are managed automatically by this
                              app's lifespan (no external lifespan hook is
                              exposed, the entire app is built inside here;
                              see the comment in the lifespan for why).
                              Protects BOTH {plain_path} AND {stls_path} —
                              not just the encrypted channel (same behavior
                              as stls-a2a). The handshake endpoints stay
                              always open, by design.

    Returns:
        ASGI app ready to be served with uvicorn (uvicorn.run(app, ...)
        or `uvicorn app_module:app`), with:
            - {plain_path}  → standard MCP, generated by the SDK
            - {stls_path}   → STLS-encrypted MCP
            - {HANDSHAKE_PATH} → STLS handshake (HMAC challenge/response)
        Not a direct Starlette instance but a thin ASGI wrapper
        (_ExactMountPathNormalizer) around it — see that class for why
        it's necessary. uvicorn/Starlette/ASGI servers don't
        distinguish: any valid ASGI callable works.

    Example:
        from mcp.server.fastmcp import FastMCP
        from stls_core.providers import KeySessionProviderFactory, KeySessionProvider
        from stls_mcp import create_secure_mcp_app

        mcp = FastMCP("My Server", stateless_http=True, json_response=True)

        @mcp.tool()
        def add(a: int, b: int) -> int:
            return a + b

        provider = KeySessionProviderFactory().get_session_provider(
            session_type=KeySessionProvider.KeySessionProviderType.SERVER,
            port=8091,
        )

        app = create_secure_mcp_app(mcp, provider)
        # uvicorn.run(app, host="0.0.0.0", port=8000)
    """
    cache = session_cache or SessionCacheFactory.build()

    # ── Standard app, generated and managed entirely by the official SDK ──────
    plain_app = mcp.streamable_http_app()

    # ── Encrypted middleware, same session manager, internal forwarding ──────
    # NOTE: uses the "bare" plain_app (without the auth gate) — StlsMcpMiddleware
    # internally forwards every decrypted request to this same instance; if
    # it were the protected one, every encrypted request would get
    # authenticated twice (once inbound on MCP_STLS_PATH, once on the
    # internal forward with the same headers — redundant, not a security
    # problem but needless double work on every call). The auth gate only
    # goes on the two external exposures, built right below.
    stls_app = StlsMcpMiddleware(plain_app, cache, stls_path=stls_path, plain_path=plain_path)

    # ── Auth gate — applied ONLY to the two external exposures ───────────────
    # (the "bare" plain_app above stays shared and unprotected for
    # StlsMcpMiddleware's internal forwarding). If auth and api_key_manager
    # are both None, wrap_with_auth returns the app unchanged — no overhead.
    guarded_plain_app = wrap_with_auth(plain_app, auth=auth, api_key_manager=api_key_manager)
    guarded_stls_app = wrap_with_auth(stls_app, auth=auth, api_key_manager=api_key_manager)

    # ── Standard STLS handshake endpoint (HMAC challenge/response) ────────
    async def handshake_endpoint(request: Request) -> JSONResponse:
        try:
            body = await request.json()
            handshake_request = HandshakeRequest.model_validate(body)
        except Exception as exc:
            return JSONResponse(
                {"jsonrpc": "2.0", "error": {"code": -32600, "message": f"Invalid request: {exc}"}, "id": None},
                status_code=400,
            )

        try:
            response = await perform_handshake(handshake_request, key_session_provider, cache)
        except HandshakeError as exc:
            logger.warning("Handshake failed: %s", exc.message)
            status = 400 if exc.code == -32600 else 503
            return JSONResponse(
                {"jsonrpc": "2.0", "error": {"code": exc.code, "message": exc.message}, "id": None},
                status_code=status,
            )

        return JSONResponse(response.model_dump())

    # ── Routes: built dynamically based on the active provider ──────────────
    provider_name = os.getenv("KEY_PROVIDER_NAME", "base").strip().lower()
    routes = [Route(HANDSHAKE_PATH, handshake_endpoint, methods=["POST"])]

    # Additional PQC endpoint — registered only when KEY_PROVIDER_NAME=pqc.
    # The StlsMcpMiddleware is agnostic to the handshake type: sessions
    # created by /stls/pqc/handshake end up in the same session_cache and
    # are accessible via the identical X-STLS-Session-ID.
    if provider_name == "pqc":
        from stls_core import PQCHandshakeRequest, PQCHandshakeError, perform_pqc_handshake

        async def pqc_handshake_endpoint(request: Request) -> JSONResponse:
            try:
                body = await request.json()
                pqc_request = PQCHandshakeRequest.model_validate(body)
            except Exception as exc:
                return JSONResponse(
                    {"jsonrpc": "2.0", "error": {"code": -32600, "message": f"Invalid request: {exc}"}, "id": None},
                    status_code=400,
                )

            try:
                response = await perform_pqc_handshake(pqc_request, cache)
            except PQCHandshakeError as exc:
                logger.warning("PQC handshake failed: %s", exc.message)
                status = 400 if exc.code == -32600 else 503
                return JSONResponse(
                    {"jsonrpc": "2.0", "error": {"code": exc.code, "message": exc.message}, "id": None},
                    status_code=status,
                )

            return JSONResponse(response.model_dump())

        routes.append(Route(HANDSHAKE_PQC_PATH, pqc_handshake_endpoint, methods=["POST"]))
        logger.info("stls-mcp: PQC endpoint registered on %s", HANDSHAKE_PQC_PATH)

    routes += [
        Mount(stls_path, app=guarded_stls_app),
        Mount("/", app=guarded_plain_app),
    ]

    # ── Lifespan: propagates the SDK's session_manager.run() ──────────────────
    # Critical detail verified experimentally against mcp>=1.27: the
    # Starlette app returned by streamable_http_app() doesn't expose a
    # direct `.lifespan` attribute (only valid for the
    # FastAPI(lifespan=...) pattern documented in older examples) — the
    # session manager's context manager lives on
    # `app.router.lifespan_context`. Without correctly propagating it, the
    # session manager never starts and all requests (plain AND encrypted,
    # because they share the same session manager) fail silently or with
    # cryptic client-side errors.
    plain_app_lifespan = plain_app.router.lifespan_context

    @asynccontextmanager
    async def lifespan(app: Starlette) -> AsyncIterator[None]:
        async with plain_app_lifespan(plain_app):
            # api_key_manager: unlike stls-a2a (where the caller builds its
            # own FastAPI lifespan and slips in `await manager.start()`
            # upstream — create_secure_a2a_endpoint expects an instance
            # that is ALREADY started), here there is no external lifespan
            # hook: the entire app, lifespan included, is built INSIDE this
            # function. That's why the lifecycle is deliberately reversed:
            # pass an instance that is NOT yet started, and this lifespan
            # manages its start/stop.
            if api_key_manager is not None:
                await api_key_manager.start()
            try:
                logger.info(
                    "stls-mcp started: plain=%s stls=%s handshake=%s",
                    plain_path, stls_path, HANDSHAKE_PATH,
                )
                yield
            finally:
                if api_key_manager is not None:
                    await api_key_manager.stop()

    app = Starlette(
        routes=routes,
        lifespan=lifespan,
    )

    # Workaround for Starlette's quirk on Mount + exact path without a
    # trailing slash — see _ExactMountPathNormalizer for details. Without
    # this, "POST {stls_path}" (as typically called by an MCP client)
    # would be incorrectly routed to Mount("/", app=plain_app) instead of
    # the STLS middleware.
    return _ExactMountPathNormalizer(app, stls_path)


def stls_capabilities_fragment(
    *,
    key_provider_name: str = "base",
    endpoint: str = MCP_STLS_PATH,
) -> dict:
    """
    Builds the fragment to insert into capabilities.experimental.stls in
    the initialize() response — used by the extension's discovery.

    For the PQC provider, key_derivation and handshakeEndpoint reflect
    the hybrid X25519 + ML-KEM-768 protocol.
    """
    from .stls_mcp_constants import STLS_EXTENSION_KEY

    if key_provider_name == "pqc":
        key_derivation = "HKDF-SHA256+X25519+ML-KEM-768"
        handshake_endpoint = HANDSHAKE_PQC_PATH
    else:
        key_derivation = "HKDF-Expand-SHA256"
        handshake_endpoint = HANDSHAKE_PATH

    return {
        STLS_EXTENSION_KEY: {
            "version": "1.0",
            "encryption": "AES-256-GCM",
            "hmac": "HMAC-SHA256",
            "keyDerivation": key_derivation,
            "keyProvider": key_provider_name,
            "endpoint": endpoint,
            "handshakeEndpoint": handshake_endpoint,
        }
    }
