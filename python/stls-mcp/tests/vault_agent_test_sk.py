"""
vault_agent_test_sk.py
------------------------
Semantic Kernel test agent against vault_server.py (Deep Sky Vault), in
two modes:

    plain    -> standard MCPStreamableHttpPlugin against /mcp, no encryption.
    --secure -> same MCPStreamableHttpPlugin, but with an STLS-encrypted
                httpx_client_factory injected into the constructor,
                against /mcp-stls (handshake + AES-256-GCM traffic).

Third of three variants of the same test (ADK: vault_agent_test.py,
LangChain/LangGraph: vault_agent_test_lg.py) — same server, same tool
set, same plain/secure comparison. Like LangChain, and unlike ADK,
NEITHER variant requires a workaround: MCPStreamableHttpPlugin forwards
unrecognized **kwargs directly to
mcp.client.streamable_http.streamablehttp_client (see
get_mcp_client() in the official source,
semantic_kernel/connectors/mcp.py) — httpx_client_factory passed to the
plugin's constructor therefore reaches the official MCP layer intact,
exactly like with langchain-mcp-adapters. No dependency on google-adk
in this file.

Running it:
    # Terminal 1 — the server (unchanged, start it first)
    python vault_server.py
    # or, for the PQC-encrypted channel:
    KEY_PROVIDER_NAME=pqc python vault_server.py

    # Terminal 2 — this script
    pip install semantic-kernel openai
    export OPENAI_API_KEY=...
    python vault_agent_test_sk.py                # plain, against /mcp
    python vault_agent_test_sk.py --secure        # PQC-encrypted, against /mcp-stls

Environment variables:
    VAULT_BASE_URL         base URL of the server (default: http://127.0.0.1:8765)
    STLS_CLIENT_ID         client_id for the handshake (default: vault-agent-test-sk)
    KEY_PROVIDER_NAME      Provider for --secure when != pqc (default: pqc).
                            With "base"/"arqit_py" it resolves the session_key
                            from its own KeySessionProvider — it must match
                            the server's, otherwise the handshake fails on
                            the proof-of-possession (not a silent mismatch;
                            the same behavior already seen with stls-a2a
                            and with the other two variants of this same
                            test).
    OPENAI_API_KEY          required by OpenAIChatCompletion.
    OPENAI_CHAT_MODEL_ID    defaults to "gpt-4o-mini" if unset.

NOTE on choosing OpenAI instead of Gemini (unlike the other two
variants, ADK and LangChain, which use gemini-2.5-flash): Semantic
Kernel's GoogleAIChatCompletion connector internally relies on the
DEPRECATED google.generativeai package, whose protobuf Schema doesn't
recognize the "title" field — present by spec in every JSON Schema
property generated by FastMCP/pydantic for MCP tools. The result is a
crash ("Unknown field for Schema: title") on the very first call
involving a tool, independent of STLS/MCP (which has already worked at
that point: initialize/list_tools completed successfully) — a known
bug, also reproduced on langchain_google_genai with the same underlying
package (https://github.com/langchain-ai/langchain/issues/28568).
OpenAIChatCompletion doesn't have this limitation (standard JSON
Schema, "title" included, no problem). If semantic-kernel ever migrates
the Google connector to the new google.genai package, going back to
Gemini for consistency with the other two variants should be possible
again with no other changes.

NOTE only partially verified: the most recent official documentation
(microsoft/semantic-kernel README) shows ChatCompletionAgent(plugins=[...])
invoking tools with no further configuration. Older sources instead
show the need to explicitly enable
settings.function_choice_behavior = FunctionChoiceBehavior.Auto() via
KernelArguments. This script follows the more recent pattern (no extra
configuration); if in practice tools aren't invoked, that's the first
thing to check.
"""

from __future__ import annotations

import argparse
import asyncio
import logging
import os

from dotenv import load_dotenv
from semantic_kernel.agents import ChatCompletionAgent, ChatHistoryAgentThread
from semantic_kernel.connectors.ai.open_ai import OpenAIChatCompletion
from semantic_kernel.connectors.mcp import MCPStreamableHttpPlugin

from stls_mcp import (
    perform_client_handshake,
    perform_pqc_client_handshake,
    stls_httpx_factory,
)

load_dotenv()

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s-%(levelname)-8s-%(name)s-%(message)s",
    datefmt="%Y-%m-%dT%H:%M:%S",
)
logger = logging.getLogger(__name__)

PLUGIN_NAME = "Vault"

SYSTEM_PROMPT = (
    "You are a fleet operations agent for the Deep Sky Vault. "
    "Use the available tools to answer questions about the fleet — "
    "never make up station data. Keep answers concise."
)

# Same round of prompts as the other two variants, for a direct comparison.
TEST_PROMPTS = [
    "List all stations currently in the fleet.",
    "What's the detailed status of kepler-9?",
    "Decode the latest incoming transmission from vega-relay.",
    "Estimate the orbital period for a station at 850 km altitude.",
]

# Same env var names as the server (vault_server.py) — if you configured
# a custom path there (e.g. MCP_STLS_PATH=/vault/mcp-stls), the client
# must read the SAME variable to stay in sync. Replaces importing the
# fixed constant from stls_mcp (which isn't env-aware). They have
# nothing to do with the handshake, which always stays at the server
# root independently of these two — see build_plugin() and VAULT_BASE_URL.
MCP_PLAIN_PATH = os.getenv("MCP_PLAIN_PATH", "/mcp")
MCP_STLS_PATH = os.getenv("MCP_STLS_PATH", "/mcp-stls")

# Application header for AUTH_ENABLED=true on the server side — see the
# equivalent comment in vault_agent_test.py. None = no header sent.
VAULT_API_KEY = os.getenv("VAULT_API_KEY")


async def build_plugin(*, secure: bool, base_url: str) -> MCPStreamableHttpPlugin:
    """Builds the plain or encrypted MCP plugin depending on the --secure flag.

    The returned plugin is NOT connected yet — it must be used with
    `async with` (MCPPluginBase.__aenter__/__aexit__ call
    connect()/close()), not just instantiated.
    """
    if not secure:
        logger.info("PLAIN plugin against %s%s", base_url, MCP_PLAIN_PATH)
        return MCPStreamableHttpPlugin(
            name=PLUGIN_NAME,
            url=f"{base_url}{MCP_PLAIN_PATH}",
            headers={"X-API-Key": VAULT_API_KEY} if VAULT_API_KEY else None,
        )

    provider = os.getenv("KEY_PROVIDER_NAME", "pqc").strip().lower()
    client_id = os.getenv("STLS_CLIENT_ID", "vault-agent-test-sk")

    if provider == "pqc":
        session_id, transport = await perform_pqc_client_handshake(
            base_url, client_id=client_id,
        )
    else:
        # base/arqit_py: the session_key must be resolved from its own
        # KeySessionProvider BEFORE the handshake — exactly like
        # vault_server.py does to build its own SERVER provider. It must
        # be the same provider as the server's, or the handshake will
        # fail on the proof-of-possession (not a silent mismatch).
        #
        # Do NOT use KeySessionProviderFactory.resolve_if_awaitable()
        # here: it calls asyncio.run() internally, meant for synchronous
        # callers with no event loop already running. build_plugin() is
        # already async, running inside this script's
        # asyncio.run(main()) — a second, nested asyncio.run() raises a
        # RuntimeError ("cannot be called from a running event loop",
        # seen in the ADK variant of this same test).
        # getSessionKeyIdentifier()/getSessionKeyData() are always
        # coroutines by ABC contract (KeySessionProvider in
        # stls_core_providers_base.py), so they're awaited directly.
        from stls_core import KeySessionProviderFactory
        from stls_core.providers.stls_core_providers_base import KeySessionProvider

        key_session_provider = KeySessionProviderFactory().get_session_provider(
            session_type=KeySessionProvider.KeySessionProviderType.CLIENT,
            host="localhost",
            port=int(os.getenv("KEY_SESSION_PORT", "8091")),
        )
        kid = await key_session_provider.getSessionKeyIdentifier()
        session_key = await key_session_provider.getSessionKeyData(kid)
        session_id, transport = await perform_client_handshake(
            base_url, session_key, client_id=client_id,
        )

    logger.info(
        "ENCRYPTED plugin (provider=%s) against %s%s", provider, base_url, MCP_STLS_PATH
    )

    # No ADK dependency here, and no subclassing like with ADK:
    # httpx_client_factory ends up in
    # MCPStreamableHttpPlugin._client_kwargs and is forwarded as-is to
    # streamablehttp_client(**args) — see
    # MCPStreamableHttpPlugin.get_mcp_client() in the official source.
    factory = stls_httpx_factory(session_id, transport, stls_path=MCP_STLS_PATH)

    return MCPStreamableHttpPlugin(
        name=PLUGIN_NAME,
        url=f"{base_url}{MCP_STLS_PATH}",
        httpx_client_factory=factory,
        headers={"X-API-Key": VAULT_API_KEY} if VAULT_API_KEY else None,
    )


async def main() -> None:
    parser = argparse.ArgumentParser(description="Vault agent test — Semantic Kernel (plain/secure)")
    parser.add_argument(
        "--secure",
        action="store_true",
        help="Use the STLS encrypted channel (/mcp-stls) instead of plain (/mcp).",
    )
    args = parser.parse_args()

    base_url = os.getenv("VAULT_BASE_URL", "http://127.0.0.1:8765").rstrip("/")
    model_id = os.getenv("OPENAI_CHAT_MODEL_ID", "gpt-4o-mini")

    print("\n" + "=" * 60)
    print(f"Vault Agent Test (Semantic Kernel) — {'ENCRYPTED (STLS)' if args.secure else 'PLAIN'} mode")
    print("=" * 60)
    print(f"  Server : {base_url}")
    print()

    plugin = await build_plugin(secure=args.secure, base_url=base_url)

    async with plugin:
        agent = ChatCompletionAgent(
            service=OpenAIChatCompletion(ai_model_id=model_id),
            name="vault_operator",
            instructions=SYSTEM_PROMPT,
            plugins=[plugin],
        )

        thread: ChatHistoryAgentThread | None = None
        for i, prompt in enumerate(TEST_PROMPTS, start=1):
            print(f"── Prompt {i}/{len(TEST_PROMPTS)} " + "─" * 40)
            print(f"  👤 {prompt}")

            response = await agent.get_response(messages=prompt, thread=thread)
            thread = response.thread
            print(f"  🤖 {response.content}\n")

    print("=" * 60)
    print("Test completed.")
    print("=" * 60)


if __name__ == "__main__":
    asyncio.run(main())
