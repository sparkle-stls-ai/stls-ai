# ── Session store ─────────────────────────────────────────────────────────────
# SESSION_CACHE_BACKEND    memory (default) | redis  — same switch as
#                          stls_core.SessionCacheFactory server-side.
# SESSION_CACHE_REDIS_URL  redis://localhost:6379
# SESSION_CACHE_REDIS_NAMESPACE  stls:sc  (Redis key prefix, distinct from
#                          the keystore's stls:ks:* — see stls_core_session.py)
# SESSION_CACHE_TTL        idle timeout, seconds (sliding window)

SESSION_CACHE_TTL = int(os.getenv("SESSION_CACHE_TTL", "3600"))
_KEY_PROVIDER = os.getenv("KEY_PROVIDER_NAME", "base").strip().lower()


@dataclass
class KeySession:
    key_identifier: str
    key_data:       bytes
    agent_name:     str | None = None

    @property
    def is_ready(self) -> bool:
        """
        True if the session has a key available.
        False for placeholder PQC sessions created by /secure/connect
        before the KEM handshake happens on the first /secure/send.
        """
        return bool(self.key_data)


class _MemoryKeySessionCache:
    """
    In-process cache with a sliding-window TTL. Default backend — suited to
    local development and single-instance deployments, but it does not survive
    a process restart or multi-instance scale-out (use redis on Cloud Run).
    The PQC lock is local: sufficient because there is no concurrency across
    different processes with this backend.
    """

    def __init__(self, ttl: int) -> None:
        self._ttl = ttl
        self._store: dict[str, tuple[KeySession, float]] = {}
        self._store_lock = asyncio.Lock()
        self._pqc_locks: dict[str, asyncio.Lock] = {}

    async def save(self, session_id: str, session: KeySession) -> None:
        async with self._store_lock:
            self._store[session_id] = (session, time.monotonic())

    async def load(self, session_id: str) -> KeySession | None:
        async with self._store_lock:
            entry = self._store.get(session_id)
            if entry is None:
                return None
            session, last_touch = entry
            if time.monotonic() - last_touch > self._ttl:
                del self._store[session_id]
                return None
            self._store[session_id] = (session, time.monotonic())  # sliding TTL
            return session

    async def touch(self, session_id: str) -> bool:
        return await self.load(session_id) is not None

    async def delete(self, session_id: str) -> None:
        async with self._store_lock:
            self._store.pop(session_id, None)
        self._pqc_locks.pop(session_id, None)

    async def count(self) -> int:
        async with self._store_lock:
            return len(self._store)

    def lock(self, session_id: str) -> asyncio.Lock:
        if session_id not in self._pqc_locks:
            self._pqc_locks[session_id] = asyncio.Lock()
        return self._pqc_locks[session_id]


class _RedisKeySessionCache:
    """
    Redis-backed — for Cloud Run (multi-instance / scale-to-zero): a session
    created on one instance stays valid on the next request even if it lands
    on a different instance.

    Wire format compatible with stls_core.RedisSessionCache (server-side),
    same {namespace}:{session_id} prefix and same JSON envelope, for
    operational consistency — but it is a separate implementation: the
    server-side SessionCacheBase returns a ready StlsTransport with the raw
    session_key already discarded, whereas here the raw key is needed on every
    call to rebuild SecureA2ATransportAdapter (base_url changes on every
    request, so the adapter is never reused across calls).
    """

    def __init__(self, url: str, namespace: str, ttl: int) -> None:
        self._redis = redis.Redis.from_url(url, decode_responses=False)
        self._ns = namespace
        self._ttl = ttl

    def _key(self, session_id: str) -> str:
        return f"{self._ns}:{session_id}"

    async def ping(self) -> None:
        await self._redis.ping()

    async def aclose(self) -> None:
        await self._redis.aclose()

    async def save(self, session_id: str, session: KeySession) -> None:
        payload = json.dumps({
            "session_key": base64.b64encode(session.key_data).decode(),
            "kid":         session.key_identifier,
            "agent_name":  session.agent_name or "",
            "created_at":  time.time(),
        })
        await self._redis.set(self._key(session_id), payload, ex=self._ttl)

    async def load(self, session_id: str) -> KeySession | None:
        # GETEX renews the idle TTL on every read (sliding window)
        raw = await self._redis.getex(self._key(session_id), ex=self._ttl)
        if raw is None:
            return None
        data = json.loads(raw)
        return KeySession(
            key_identifier=data["kid"],
            key_data=base64.b64decode(data["session_key"]) if data["session_key"] else b"",
            agent_name=data.get("agent_name") or None,
        )

    async def touch(self, session_id: str) -> bool:
        return bool(await self._redis.expire(self._key(session_id), self._ttl))

    async def delete(self, session_id: str) -> None:
        await self._redis.delete(self._key(session_id))

    async def count(self) -> int:
        n = 0
        async for _ in self._redis.scan_iter(match=f"{self._ns}:*", count=100):
            n += 1
        return n

    def lock(self, session_id: str):
        return self._redis.lock(f"{self._ns}:lock:{session_id}", timeout=30, blocking_timeout=35)


def _build_session_cache() -> "_MemoryKeySessionCache | _RedisKeySessionCache":
    backend = os.getenv("SESSION_CACHE_BACKEND", "memory").strip().lower()
    if backend == "redis":
        url = os.getenv("SESSION_CACHE_REDIS_URL", "redis://localhost:6379")
        namespace = os.getenv("SESSION_CACHE_REDIS_NAMESPACE", "stls:sc")
        return _RedisKeySessionCache(url, namespace, SESSION_CACHE_TTL)
    if backend == "memory":
        return _MemoryKeySessionCache(SESSION_CACHE_TTL)
    raise ValueError(
        f"SESSION_CACHE_BACKEND='{backend}' not recognized. "
        "Supported values: 'memory' (default), 'redis'."
    )


_cache = _build_session_cache()


# ── Key session initialisation ─────────────────────────────────────────────────

async def _init_key_session(session_id: str, agent_name: str | None) -> KeySession:
    """
    Creates a KeySession for session_id.

    base / arqit_py: resolves kid and key_data immediately via KeySessionProviderFactory.
    pqc:             creates an empty placeholder — the KEM handshake happens
                     lazily on the first /secure/send or /secure/stream (which
                     provides the server URL needed for the handshake).
    """
    if _KEY_PROVIDER == "pqc":
        session = KeySession(
            key_identifier="",   # popolato dal KEM handshake
            key_data=b"",        # popolato dal KEM handshake
            agent_name=agent_name,
        )
        await _cache.save(session_id, session)
        logger.info(
            "PQC key session placeholder created  session_id=%s  agent=%s",
            session_id, agent_name or "<unspecified>",
        )
        return session

    # ── base / arqit_py: unchanged flow ────────────────────────────────────
    host = os.getenv("KEY_SESSION_HOST", "localhost")
    port = int(os.getenv("KEY_SESSION_PORT", "8081"))

    provider: KeySessionProvider = KeySessionProviderFactory().get_session_provider(
        session_type=KeySessionProvider.KeySessionProviderType.CLIENT,
        host=host,
        port=port,
    )

    key_identifier = await provider.getSessionKeyIdentifier()
    key_data       = await provider.getSessionKeyData(key_identifier)

    session = KeySession(
        key_identifier=key_identifier,
        key_data=key_data,
        agent_name=agent_name,
    )

    await _cache.save(session_id, session)

    logger.info(
        "Key session created  provider=%s  session_id=%s  agent=%s  key_length=%d bytes",
        _KEY_PROVIDER, session_id, agent_name or "<unspecified>", len(key_data),
    )
    return session


async def _ensure_pqc_session(session_id: str, target_url: str, session: KeySession) -> KeySession:
    """
    Performs the PQC KEM handshake on the first /secure/send or /secure/stream.

    Extracts base_url from target_url (e.g. "http://host:8001/agents/x/secure-a2a"
    → "http://host:8001") and calls create_pqc_a2a_transport() to obtain
    kid and session_key. The lock coordinates concurrent handshakes on the same
    session_id: distributed on Redis (even across different instances — Cloud Run
    does not guarantee sticky routing) with the redis backend, process-local with
    the memory backend (sufficient because there is no cross-process concurrency).

    Used ONLY with _KEY_PROVIDER == "pqc".
    """
    if session.is_ready:
        return session

    async with _cache.lock(session_id):
        # Double-check: another request (even on another instance, with the
        # redis backend) may have already completed the handshake meanwhile.
        session = await _cache.load(session_id)
        if session is None:
            raise RuntimeError(f"Key session {session_id} disappeared during PQC handshake")
        if session.is_ready:
            return session

        # Extract only scheme + host:port from the agent URL
        parsed   = urlparse(target_url)
        base_url = f"{parsed.scheme}://{parsed.netloc}"

        logger.info(
            "PQC handshake starting  session_id=%s  base_url=%s  agent=%s",
            session_id, base_url, session.agent_name or "<unspecified>",
        )
        try:
            adapter = await create_pqc_a2a_transport(
                base_url,
                client_id=f"secure-transport-{session_id[:8]}",
            )
        except Exception as exc:
            raise RuntimeError(
                f"PQC handshake failed for session {session_id}: {exc}"
            ) from exc

        session.key_identifier = adapter.session_id
        session.key_data       = adapter.transport.session_key
        await _cache.save(session_id, session)

        logger.info(
            "PQC handshake completed  session_id=%s  kid=%s  key_length=%d bytes",
            session_id, session.key_identifier, len(session.key_data),
        )

    return session


async def _get_session(session_id: str) -> KeySession:
    session = await _cache.load(session_id)
    if session is None:
        raise HTTPException(status_code=503, detail=f"Key session not found or expired: {session_id}")
    return session


# ── FastAPI app ────────────────────────────────────────────────────────────────

@asynccontextmanager
async def _lifespan(app: FastAPI):
    if isinstance(_cache, _RedisKeySessionCache):
        await _cache.ping()
    logger.info(
        "Secure transport started  session_cache_backend=%s  session_cache_ttl=%ds  provider=%s",
        os.getenv("SESSION_CACHE_BACKEND", "memory").strip().lower(), SESSION_CACHE_TTL, _KEY_PROVIDER,
    )
    yield
    if isinstance(_cache, _RedisKeySessionCache):
        await _cache.aclose()


app = FastAPI(title="Secure A2A Transport", version="2.1.0", lifespan=_lifespan)


# ── Request models ─────────────────────────────────────────────────────────────

class ConnectRequest(BaseModel):
    session_id: str
    agent_name: str | None = None


class DisconnectRequest(BaseModel):
    session_id: str


class HeartbeatRequest(BaseModel):
    session_id: str


class SecureCallRequest(BaseModel):
    session_id: str
    url:        str
    payload:    dict[str, Any]
    api_key:    str | None = None


# ── Endpoints ──────────────────────────────────────────────────────────────────

@app.get("/health")
async def health() -> dict[str, Any]:
    return {"ok": True, "active_sessions": await _cache.count()}


@app.post("/secure/connect")
async def secure_connect(req: ConnectRequest) -> dict[str, Any]:
    """
    Initialise a new key session for the given session_id.
    If a session with the same id already exists it is replaced.
    """
    logger.info("secure_connect  session_id=%s  agent=%s", req.session_id, req.agent_name or "<unspecified>")
    try:
        session = await _init_key_session(req.session_id, req.agent_name)
        return {"ok": True, "session_id": req.session_id, "key_identifier": session.key_identifier}
    except HTTPException:
        raise
    except Exception as exc:
        logger.exception("secure_connect failed  session_id=%s", req.session_id)
        raise HTTPException(status_code=502, detail=str(exc)) from exc


@app.post("/secure/disconnect")
async def secure_disconnect(req: DisconnectRequest) -> dict[str, Any]:
    """Remove the key session immediately."""
    session = await _cache.load(req.session_id)
    await _cache.delete(req.session_id)
    if session:
        logger.info("secure_disconnect  session_id=%s  agent=%s", req.session_id, session.agent_name or "<unknown>")
    else:
        logger.warning("secure_disconnect  session_id=%s  not found (already expired?)", req.session_id)
    return {"ok": True}


@app.post("/secure/heartbeat")
async def secure_heartbeat(req: HeartbeatRequest) -> dict[str, Any]:
    """Refresh the TTL of an active session."""
    if not await _cache.touch(req.session_id):
        raise HTTPException(status_code=404, detail=f"Session not found or expired: {req.session_id}")
    return {"ok": True}


@app.post("/secure/send")
async def secure_send(req: SecureCallRequest) -> dict[str, Any]:
    """Non-streaming secure call. Returns the full jsonrpc response envelope."""
    logger.info("secure_send  session_id=%s  url=%s  method=%s", req.session_id, req.url, req.payload.get("method"))
    session = await _get_session(req.session_id)

    # PQC: run the KEM handshake on the first call (lazy)
    if _KEY_PROVIDER == "pqc" and not session.is_ready:
        try:
            session = await _ensure_pqc_session(req.session_id, req.url, session)
        except Exception as exc:
            raise HTTPException(status_code=502, detail=str(exc)) from exc

    extra_headers = {"X-API-Key": req.api_key} if req.api_key else None

    try:
        adapter = SecureA2ATransportAdapter(
            session_key=session.key_data,
            session_id=session.key_identifier,
            base_url=req.url,
        )
        safe_payload = {**req.payload, "id": 1}
        response: dict[str, Any] = await adapter.send_secure_message(safe_payload, extra_headers=extra_headers)
        if response.get("error"):
            raise HTTPException(status_code=502, detail=str(response["error"]))
        return response
    except HTTPException:
        raise
    except Exception as exc:
        logger.exception("secure_send failed  session_id=%s", req.session_id)
        raise HTTPException(status_code=502, detail=str(exc)) from exc


@app.post("/secure/stream")
async def secure_stream(req: SecureCallRequest) -> StreamingResponse:
    """
    True streaming secure call — relays each SSE event as it arrives.
    Each chunk is translated into an A2A-compatible SSE data line.
    """
    logger.info("secure_stream  session_id=%s  url=%s  method=%s", req.session_id, req.url, req.payload.get("method"))
    session = await _get_session(req.session_id)

    # PQC: run the KEM handshake on the first call (lazy)
    if _KEY_PROVIDER == "pqc" and not session.is_ready:
        try:
            session = await _ensure_pqc_session(req.session_id, req.url, session)
        except Exception as exc:
            raise HTTPException(status_code=502, detail=str(exc)) from exc

    extra_headers = {"X-API-Key": req.api_key} if req.api_key else None

    async def _generate() -> AsyncGenerator[str, None]:
        adapter = SecureA2ATransportAdapter(
            session_key=session.key_data,
            session_id=session.key_identifier,
            base_url=req.url,
        )
        safe_payload = {**req.payload, "id": 1}
        req_id: Any = req.payload.get("id", "1")

        try:
            async for chunk in adapter.stream_secure_message(safe_payload, stream_timeout=180.0, extra_headers=extra_headers):
                event = chunk.get("event", "")

                if event == "error":
                    err = {"message": chunk.get("message", "Stream error"), "code": chunk.get("code", -32603)}
                    yield f"data: {json.dumps({'error': err})}\n\n"
                    return

                if event == "TaskArtifactUpdateEvent":
                    sse_result: dict[str, Any] = {
                        "kind":      "artifact-update",
                        "taskId":    chunk.get("taskId",    ""),
                        "contextId": chunk.get("contextId", ""),
                        "artifact":  {"parts": chunk.get("parts", [])},
                        "append":    chunk.get("append",     False),
                        "lastChunk": chunk.get("last_chunk", False),
                        "final":     False,
                    }
                    yield f"data: {json.dumps({'jsonrpc': '2.0', 'id': req_id, 'result': sse_result}, default=str)}\n\n"

                elif event == "TaskStatusUpdateEvent":
                    is_final = chunk.get("final", False)
                    sse_result = {
                        "kind":      "status-update",
                        "taskId":    chunk.get("taskId",    ""),
                        "contextId": chunk.get("contextId", ""),
                        "status":    {"state": chunk.get("status", "working")},
                        "final":     is_final,
                    }
                    yield f"data: {json.dumps({'jsonrpc': '2.0', 'id': req_id, 'result': sse_result})}\n\n"
                    if is_final:
                        return

        except HTTPException as exc:
            yield f"data: {json.dumps({'error': {'message': exc.detail}})}\n\n"
        except Exception as exc:
            logger.exception("secure_stream failed  session_id=%s", req.session_id)
            yield f"data: {json.dumps({'error': {'message': str(exc)}})}\n\n"

    return StreamingResponse(
        _generate(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection":    "keep-alive",
            "X-Accel-Buffering": "no",
        },
    )


