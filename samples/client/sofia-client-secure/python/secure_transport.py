"""
Secure A2A Transport Service
============================
FastAPI microservice that wraps SecureA2ATransportAdapter for all outbound
A2A calls made by the sofia-client-secure Express backend.

Endpoints
---------
GET  /health                   liveness probe
POST /secure/connect           initialise a key session for a (user, agent) pair
POST /secure/disconnect        tear down a specific key session
POST /secure/heartbeat         refresh the TTL of a key session
POST /secure/send              non-streaming secure call  → full jsonrpc response
POST /secure/stream            streaming secure call      → SSE events

Session lifecycle
-----------------
Each (user, agent) interaction owns an independent key session identified by a
UUID session_id generated by the Express backend at connect time.

Sessions are kept by a small pluggable cache selected via SESSION_CACHE_BACKEND
("memory", the default, or "redis"), using the same env var contract as the
server-side stls_core.SessionCacheFactory (SESSION_CACHE_BACKEND/
SESSION_CACHE_REDIS_URL/SESSION_CACHE_REDIS_NAMESPACE/SESSION_CACHE_TTL) so
ops has one naming convention across the whole stls stack. On Cloud Run, use
the redis backend: consecutive requests for the same session can land on a
different instance than the one that created it, and idle instances can be
recycled at any time — an in-process cache does not survive either. Sessions
are removed:
  - explicitly, when /secure/disconnect is called;
  - automatically, when no /secure/heartbeat arrives within SESSION_CACHE_TTL
    seconds (a sliding-window idle TTL, renewed on every touch; the Express
    frontend sends a heartbeat every HEARTBEAT_INTERVAL_S seconds).

Key provider
------------
Supported providers: "base" (dev/test, fixed key), "arqit_py" (production,
Arqit SKA-Platform native Python SDK), and "pqc" (quantum-safe, hybrid
X25519 + ML-KEM-768, requires liboqs-python).

For "base" and "arqit_py", the key is resolved at /secure/connect time via
KeySessionProviderFactory — the session is immediately ready.

For "pqc", /secure/connect creates a placeholder session (no handshake yet).
The KEM handshake is performed lazily at the first /secure/send or
/secure/stream call, using the target URL to reach /stls/pqc/handshake on
the A2A server.  Subsequent calls on the same session_id reuse the
established key — no re-handshake needed until the session expires.

Note on the session cache: stls_core already ships a SessionCacheFactory with
the exact env var contract this module uses, but SessionCacheBase.get()
returns a ready-to-use StlsTransport with the raw session_key discarded —
this service needs the raw bytes on every call to rebuild
SecureA2ATransportAdapter (base_url changes per request, so the adapter is
never reused across calls). The cache below is therefore a small
reimplementation, not a direct import, kept wire-compatible with
stls_core.RedisSessionCache's Redis JSON envelope for operational parity.
"""

