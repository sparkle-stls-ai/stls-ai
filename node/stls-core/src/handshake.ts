/**
 * handshake.ts
 * ------------
 * Port of python/stls-core/src/stls_core/stls_core_handshake.py.
 *
 * STLS handshake with proof-of-key-possession via an HMAC
 * challenge/response. The key never travels over the wire — see the
 * diagram in the Python module for the full flow.
 */

import { createHmac, randomBytes, randomUUID, timingSafeEqual } from "node:crypto";
import { STLS_VERSION } from "./constants.js";
import type { KeySessionProvider } from "./providers/base.js";
import type { SessionCache } from "./session.js";

// ---------------------------------------------------------------------------
// Wire format
// ---------------------------------------------------------------------------

export interface HandshakeRequest {
  client_id: string;
  /** 32 random bytes, base64-encoded, generated by the client. Single-use. */
  nonce: string;
  protocol: string;
}

export function generateHandshakeRequest(clientId: string): HandshakeRequest {
  return {
    client_id: clientId,
    nonce: randomBytes(32).toString("base64"),
    protocol: STLS_VERSION,
  };
}

export interface HandshakeResponse {
  session_id: string;
  kid: string;
  /** HMAC-SHA256(session_key, nonce), base64-encoded. */
  proof: string;
  protocol: string;
  encryption: string;
  hmac: string;
  key_derivation: string;
}

export class HandshakeError extends Error {
  constructor(
    message: string,
    public readonly code: number = -32603,
  ) {
    super(message);
    this.name = "HandshakeError";
  }
}

// ---------------------------------------------------------------------------
// Server-side: performHandshake()
// ---------------------------------------------------------------------------

/**
 * Runs the server side of the STLS handshake. Called by the route handler
 * for POST /stls/handshake when Node acts as the STLS server.
 */
export async function performHandshake(
  request: HandshakeRequest,
  keySessionProvider: KeySessionProvider,
  sessionCache: SessionCache,
): Promise<HandshakeResponse> {
  let nonce: Buffer;
  try {
    nonce = Buffer.from(request.nonce, "base64");
    if (nonce.length < 16) {
      throw new HandshakeError(`Nonce too short: ${nonce.length} bytes (minimum 16)`, -32600);
    }
  } catch (exc) {
    if (exc instanceof HandshakeError) {
      throw exc;
    }
    throw new HandshakeError(`Nonce is not valid base64: ${(exc as Error).message}`, -32600);
  }

  const sessionId = randomUUID();

  let kid: string;
  try {
    kid = await keySessionProvider.getSessionKeyIdentifier();
    if (!kid) {
      throw new HandshakeError("getSessionKeyIdentifier() returned an empty string");
    }
  } catch (exc) {
    if (exc instanceof HandshakeError) {
      throw exc;
    }
    throw new HandshakeError(`Error retrieving the kid: ${(exc as Error).message}`);
  }

  let sessionKey: Buffer;
  try {
    sessionKey = await keySessionProvider.getSessionKeyData(kid);
  } catch (exc) {
    throw new HandshakeError(
      `Error retrieving the session key (kid=${kid}): ${(exc as Error).message}`,
    );
  }

  if (!sessionKey || sessionKey.length === 0) {
    throw new HandshakeError("Empty session key");
  }

  const proof = createHmac("sha256", sessionKey).update(nonce).digest("base64");

  try {
    await sessionCache.put(sessionId, kid, sessionKey);
  } catch (exc) {
    throw new HandshakeError(
      `Error registering the session in the cache: ${(exc as Error).message}`,
    );
  }

  return {
    session_id: sessionId,
    kid,
    proof,
    protocol: STLS_VERSION,
    encryption: "AES-256-GCM",
    hmac: "HMAC-SHA256",
    key_derivation: "HKDF-Expand-SHA256",
  };
}

// ---------------------------------------------------------------------------
// Client-side: verifyHandshakeProof()
// ---------------------------------------------------------------------------

/**
 * Verifies, on the client side, that the server holds the same key —
 * without the key ever having crossed the wire.
 */
export function verifyHandshakeProof(
  sessionKey: Buffer,
  nonce: string,
  response: HandshakeResponse,
): boolean {
  const nonceBytes = Buffer.from(nonce, "base64");
  const expectedProof = createHmac("sha256", sessionKey).update(nonceBytes).digest();
  const receivedProof = Buffer.from(response.proof, "base64");

  if (expectedProof.length !== receivedProof.length) {
    return false;
  }
  return timingSafeEqual(expectedProof, receivedProof);
}
