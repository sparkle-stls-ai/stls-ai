/**
 * providers/pqc.ts
 * ----------------
 * Port of python/stls-core/src/stls_core/providers/stls_core_providers_pqc.py.
 *
 * Hybrid X25519 + ML-KEM-768 (NIST FIPS 203) key agreement, derived
 * locally on every handshake — no external service (unlike arqit_py).
 *
 * Libraries used (in place of liboqs-python + pyca/cryptography):
 *   - ML-KEM-768: @noble/post-quantum (ml_kem768) — same FIPS 203 standard,
 *     interoperable with liboqs on the Python side at the protocol level
 *     (pubkey/ciphertext/shared secret), not internally bit-identical
 *     (different implementations of the same primitive).
 *   - X25519: @noble/curves (x25519) — RFC 7748, same library already used
 *     for ML-KEM, with a raw-bytes API that avoids the KeyObject/JWK
 *     complications of Node's native crypto module for OKP keys.
 *
 * Verified with vectors generated by real liboqs-python / pyca-cryptography
 * (not just in theory): see tests/interop/pqc-step*.ts.
 */

import { hkdfSync } from "node:crypto";
import { ml_kem768 } from "@noble/post-quantum/ml-kem.js";
import { x25519 } from "@noble/curves/ed25519.js";

import {
  KeyProvider,
  KeyProviderClient,
  KeyProviderServer,
  KeySessionProvider,
  KeySessionProviderType,
} from "./base.js";

// ---------------------------------------------------------------------------
// PQCKeyStore — in-memory store for keys derived via the KEM
// ---------------------------------------------------------------------------

export class PQCKeyStore {
  private readonly keys = new Map<string, Buffer>();

  put(kid: string, keyBytes: Buffer): void {
    this.keys.set(kid, keyBytes);
  }

  get(kid: string): Buffer | undefined {
    return this.keys.get(kid);
  }

  remove(kid: string): boolean {
    return this.keys.delete(kid);
  }

  get size(): number {
    return this.keys.size;
  }
}

// ---------------------------------------------------------------------------
// KeySessionProviderPQC
// ---------------------------------------------------------------------------

export class KeySessionProviderPQC implements KeySessionProvider {
  private kid: string | null = null;

  constructor(
    private readonly sessionType: KeySessionProviderType,
    private readonly keyStore: PQCKeyStore,
    private readonly x25519PrivateKeyBytes: Buffer | null = null,
    private mlkemSecretKeyBytes: Buffer | null = null,
  ) {}

  getSessionType(): KeySessionProviderType {
    return this.sessionType;
  }

  async getSessionKeyIdentifier(_hintKid?: string): Promise<string> {
    if (this.kid === null) {
      throw new Error(
        "[KeySessionProviderPQC] kid not available — injectKey() or setSessionKeyIdentifier() has not been called yet",
      );
    }
    return this.kid;
  }

  setSessionKeyIdentifier(kid: string): void {
    this.kid = kid;
  }

  async getSessionKeyData(sessionKeyIdentifier: string): Promise<Buffer> {
    const key = this.keyStore.get(sessionKeyIdentifier);
    if (key === undefined) {
      throw new Error(`[KeySessionProviderPQC] key not found: kid=${sessionKeyIdentifier}`);
    }
    return key;
  }

  /** Injects the key derived by performPqcHandshake() into the key store (server side). */
  injectKey(kid: string, sessionKey: Buffer): void {
    this.keyStore.put(kid, sessionKey);
    this.kid = kid;
  }

  getPeerIdentity(): string | null {
    return null;
  }

  /**
   * Derives the shared session key from this CLIENT session's own
   * ephemeral KEM private material (never exposed outside this class)
   * and the server's public contribution from its handshake response.
   * Takes already-decoded raw bytes (not the PQCHandshakeResponse DTO
   * itself) so this module has no dependency on handshake-pqc.ts's wire
   * types — that file already depends on this one for the primitives,
   * and a two-way import would be circular.
   */
  deriveSessionKey(serverX25519PublicKeyBytes: Buffer, mlkemCiphertext: Buffer, nonce: Buffer): Buffer {
    if (this.x25519PrivateKeyBytes === null || this.mlkemSecretKeyBytes === null) {
      throw new Error(
        "[KeySessionProviderPQC] deriveSessionKey() requires a CLIENT session with KEM private material (server session?)",
      );
    }
    const x25519Secret = x25519Exchange(this.x25519PrivateKeyBytes, serverX25519PublicKeyBytes);
    const mlkemSecret = mlkemDecap(this.mlkemSecretKeyBytes, mlkemCiphertext);
    return deriveHybridKey(x25519Secret, mlkemSecret, nonce);
  }

  /** Best-effort zeroing of this session's own KEM private key material. */
  destroyPrivateKeyMaterial(): void {
    this.x25519PrivateKeyBytes?.fill(0);
    if (this.mlkemSecretKeyBytes) {
      this.mlkemSecretKeyBytes.fill(0);
      this.mlkemSecretKeyBytes = null;
    }
  }
}

// ---------------------------------------------------------------------------
// KeyProviderClientPQC
// ---------------------------------------------------------------------------

export class KeyProviderClientPQC implements KeyProviderClient {
  private readonly keyStore = new PQCKeyStore();
  private session: KeySessionProviderPQC | null = null;
  private x25519PublicKeyBytes: Buffer | null = null;
  private mlkemPublicKeyBytes: Buffer | null = null;

  start(): void {
    const { secretKey: x25519Priv, publicKey: x25519Pub } = x25519GenerateKeypair();
    const { publicKey: mlkemPub, secretKey: mlkemSec } = mlkemGenerateKeypair();

    this.x25519PublicKeyBytes = x25519Pub;
    this.mlkemPublicKeyBytes = mlkemPub;

    this.session = new KeySessionProviderPQC(
      KeySessionProviderType.CLIENT,
      this.keyStore,
      x25519Priv,
      mlkemSec,
    );
  }

  createProviderSession(): KeySessionProvider {
    if (this.session === null) {
      throw new Error("[KeyProviderClientPQC] start() has not been called yet");
    }
    return this.session;
  }

  stop(): void {
    this.session?.destroyPrivateKeyMaterial();
  }

  get x25519PublicKey(): Buffer {
    if (this.x25519PublicKeyBytes === null) {
      throw new Error("[KeyProviderClientPQC] start() has not been called yet");
    }
    return this.x25519PublicKeyBytes;
  }

  get mlkemPublicKey(): Buffer {
    if (this.mlkemPublicKeyBytes === null) {
      throw new Error("[KeyProviderClientPQC] start() has not been called yet");
    }
    return this.mlkemPublicKeyBytes;
  }
}

// ---------------------------------------------------------------------------
// KeyProviderServerPQC
// ---------------------------------------------------------------------------

export class KeyProviderServerPQC implements KeyProviderServer {
  private readonly keyStore = new PQCKeyStore();
  private session: KeySessionProviderPQC | null = null;

  async start(): Promise<void> {
    this.session = new KeySessionProviderPQC(KeySessionProviderType.SERVER, this.keyStore);
  }

  createProviderSession(): KeySessionProvider {
    if (this.session === null) {
      throw new Error("[KeyProviderServerPQC] start() has not been called yet");
    }
    return this.session;
  }

  async stop(): Promise<void> {}
}

// ---------------------------------------------------------------------------
// KeyProviderPQC — factory
// ---------------------------------------------------------------------------

export class KeyProviderPQC implements KeyProvider {
  getName(): string {
    return "pqc";
  }

  createProviderClient(
    _host: string,
    _port: number,
    _options: Record<string, unknown>,
  ): KeyProviderClient {
    return new KeyProviderClientPQC();
  }

  createProviderServer(_port: number, _options: Record<string, unknown>): KeyProviderServer {
    return new KeyProviderServerPQC();
  }
}

// ---------------------------------------------------------------------------
// PQC cryptographic functions — public API
// ---------------------------------------------------------------------------

export function mlkemGenerateKeypair(): { publicKey: Buffer; secretKey: Buffer } {
  const { publicKey, secretKey } = ml_kem768.keygen();
  return { publicKey: Buffer.from(publicKey), secretKey: Buffer.from(secretKey) };
}

export function mlkemEncap(clientMlkemPublicKey: Buffer): {
  ciphertext: Buffer;
  sharedSecret: Buffer;
} {
  const { cipherText, sharedSecret } = ml_kem768.encapsulate(clientMlkemPublicKey);
  return { ciphertext: Buffer.from(cipherText), sharedSecret: Buffer.from(sharedSecret) };
}

export function mlkemDecap(clientMlkemSecretKey: Buffer, ciphertext: Buffer): Buffer {
  const sharedSecret = ml_kem768.decapsulate(ciphertext, clientMlkemSecretKey);
  return Buffer.from(sharedSecret);
}

export function x25519GenerateKeypair(): { secretKey: Buffer; publicKey: Buffer } {
  const { secretKey, publicKey } = x25519.keygen();
  return { secretKey: Buffer.from(secretKey), publicKey: Buffer.from(publicKey) };
}

export function x25519Exchange(privateKeyBytes: Buffer, peerPublicKeyBytes: Buffer): Buffer {
  return Buffer.from(x25519.getSharedSecret(privateKeyBytes, peerPublicKeyBytes));
}

/**
 * Derives the final session_key from the two shared secrets via full
 * HKDF-SHA256 (Extract + Expand, RFC 5869) — unlike the AES/HMAC keys
 * derived by StlsTransport (see crypto.ts), which use Expand only. Here
 * `node:crypto.hkdfSync` is the correct choice because it exactly
 * replicates `cryptography.hazmat.primitives.kdf.hkdf.HKDF`
 * (extract+expand) used on the Python side — not HKDFExpand.
 */
export function deriveHybridKey(
  x25519Secret: Buffer,
  mlkemSecret: Buffer,
  nonce: Buffer,
  info: Buffer = Buffer.from("stls-pqc-hybrid-v1", "utf-8"),
  length = 32,
): Buffer {
  const ikm = Buffer.concat([x25519Secret, mlkemSecret]);
  const derived = hkdfSync("sha256", ikm, nonce, info, length);
  return Buffer.from(derived);
}
